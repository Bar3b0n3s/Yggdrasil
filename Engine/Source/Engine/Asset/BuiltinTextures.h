#pragma once

#include "Engine/Asset/TextureData.h"
#include "Engine/Core/Base.h"

#include <cstdint>
#include <string_view>

// The procedural built-in textures (Architecture §7.1: engine://Textures/{White, Black, FlatNormal, Checker, Missing}, and
// M21's sprite textures).
// The renderer binds White, FlatNormal and Black for empty material slots (§8.4); Missing is the texture placeholder (§7.2).

namespace Engine {

	enum class BuiltinTexture : uint8_t
	{
		White,      // 4x4 RGBA8Srgb (255, 255, 255, 255)
		Black,      // 4x4 RGBA8Srgb (0, 0, 0, 255)
		FlatNormal, // 4x4 RGBA8Unorm (128, 128, 255, 255): the tangent-space normal (0, 0, 1)
		Checker,    // 64x64 RGBA8Srgb, 8x8-texel squares of light and dark grey, full mip chain
		Missing,    // 64x64 RGBA8Srgb, 8x8-texel squares of magenta and black, full mip chain: obvious on any surface
		// M21 (Docs/Decisions/0032-m21-contract.md decision 7): the procedural sprite textures, engine://Textures/<Name>
		// (BuiltinAssetHandles::Sprite*Texture), generated by GenerateBuiltinSpriteTexture: 16 x 16 RGBA8Srgb, one mip level
		// (sprites sample without mips), never compressed, white shapes whose transparent texels are (255, 255, 255, 0) so a
		// linear sampler blends no dark fringe. Texel (x, y) has its centre at (x + 0.5, y + 0.5), y down.
		SpriteSquare,  // every texel (255, 255, 255, 255)
		SpriteRounded, // the square with its four corners rounded to a radius of 4 texels: a texel in a corner's 4 x 4 block is
					   // transparent when its centre lies farther than 4 texels from that corner's circle centre ((4, 4),
					   // (12, 4), (4, 12), (12, 12))
		SpriteBevel,   // opaque grey levels of a raised tile, with d1 = min(x, y) and d2 = min(15 - x, 15 - y): 255 where d1 < 2
					   // and d1 <= d2 (the lit top and left edges), else 128 where d2 < 2 (the shaded bottom and right edges),
					   // else 204 (the face); the three values are sRGB-encoded and repeated in R, G and B
		SpriteCircle,  // a disc of radius 8 texels centred at (8, 8): opaque where (2x + 1 - 16)^2 + (2y + 1 - 16)^2 <= 256
		// M26 (C26.1, C-PART; Docs/Decisions/0037-m26-contract.md decision 7): engine://Textures/Particle
		// (BuiltinAssetHandles::ParticleTexture, ADR 0028's phase-3 ledger's 0x018b), the particles' default texture, generated
		// by GenerateBuiltinParticleTexture: 32 x 32 RGBA8Srgb, one mip level, never compressed, a white soft disc whose texel
		// (x, y) has alpha round(255 * max(0, 1 - d^2)^2) with d = the distance of its centre (x + 0.5, y + 0.5) from (16, 16) over
		// 16, computed in integer arithmetic on (2x + 1 - 32)^2 + (2y + 1 - 32)^2 against 1024 (colour (255, 255, 255))
		Particle,
		// M31 (Docs/Decisions/0046-m31-material-parameters.md decision 6; ADR 0042's phase-5 ledger's 0x018c):
		// engine://Textures/DissolveNoise (BuiltinAssetHandles::DissolveNoiseTexture), the noise a MaterialParameters dissolve
		// clips by, generated by GenerateBuiltinDissolveNoiseTexture: 128 x 128 R8Unorm, one mip level, never compressed, a
		// smooth noise that tiles in both directions (three octaves of value noise on lattices of 4, 8 and 16 cells a side,
		// weighted 4, 2 and 1, each lattice wrapping), equalized so that its 16384 texels take the values 1 to 254 in equal
		// shares (64 or 65 texels each, by rank, ties by texel index): a dissolve of amount a removes about the share a of a
		// surface, nothing at 0 and everything at 1
		DissolveNoise,
		// M47 (Docs/Decisions/0065-m47-water.md decision 3; phase 8's ledger's 0x018d and 0x018e): engine://Textures/WaterNormal
		// and WaterFoam (BuiltinAssetHandles::WaterNormalTexture and WaterFoamTexture), the water's default detail normals and
		// foam, generated by GenerateBuiltinWaterNormalTexture and GenerateBuiltinWaterFoamTexture: 128 x 128, never compressed,
		// each with its full mip chain (exact 2 x 2 box means), tiling in both directions, from four (normals) and three (foam)
		// octaves of value noise on wrapping lattices (each lattice point an integer hash, a fixed-point smoothstep blend)
		WaterNormal, // RGBA8Unorm: the tangent-space normal of the noise as a height field, (x, y) in R and G, z in B, A 255
		WaterFoam    // R8Unorm: the noise past a threshold, 0 clear water to 255 dense foam
	};

	// "White", "Black", ...; the name in engine://Textures/<Name>. "Unknown" for a value outside the enumeration (a pure
	// name lookup, like FieldTypeToString). Pure and thread-safe.
	[[nodiscard]] std::string_view BuiltinTextureToString(BuiltinTexture texture);

	// Generates `texture` deterministically (integer arithmetic only; mips by exact 2x2 box filtering of the sRGB-decoded
	// values through a fixed table, so the bytes never depend on the C runtime). The result passes ValidateTextureData. The
	// sprite textures (M21) come from GenerateBuiltinSpriteTexture.
	[[nodiscard]] TextureData GenerateBuiltinTexture(BuiltinTexture texture);

	// M21 (Docs/Decisions/0032-m21-contract.md decision 7, stream B): the sprite texture `texture` (SpriteSquare to
	// SpriteCircle, asserted), as the enumerators' comments define it, in integer arithmetic only, so its bytes are identical
	// in every configuration. The result passes ValidateTextureData.
	[[nodiscard]] TextureData GenerateBuiltinSpriteTexture(BuiltinTexture texture);

	// M26 (C26.1; Docs/Decisions/0037-m26-contract.md decision 7, stream P-B): the particle texture, as BuiltinTexture::Particle's
	// comment defines it, in integer arithmetic only, so its bytes are identical in every configuration. The result passes
	// ValidateTextureData. Stream P-B adds its catalogue entries (Resources/EngineAssets.json, kept sorted by handle, and the
	// procedural table of BuiltinAssets.cpp).
	[[nodiscard]] TextureData GenerateBuiltinParticleTexture();

	// M31 (Docs/Decisions/0046-m31-material-parameters.md decision 6): the dissolve noise, as BuiltinTexture::DissolveNoise's
	// comment defines it, in integer arithmetic only (an integer hash per lattice point, a fixed-point smoothstep blend), so
	// its bytes are identical in every configuration. The result passes ValidateTextureData.
	[[nodiscard]] TextureData GenerateBuiltinDissolveNoiseTexture();

	// M47 (Docs/Decisions/0065-m47-water.md decision 3): the water's normal map and foam map, as BuiltinTexture::WaterNormal's
	// and WaterFoam's comments define them, in integer arithmetic only (the normal's length an exact integer square root), so
	// their bytes are identical in every configuration. Each result passes ValidateTextureData.
	[[nodiscard]] TextureData GenerateBuiltinWaterNormalTexture();
	[[nodiscard]] TextureData GenerateBuiltinWaterFoamTexture();

}
