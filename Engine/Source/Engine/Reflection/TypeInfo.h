	// An owned, type-erased object created by TypeOps::Create (a default-constructed instance of the reflected type).
	using ObjectDeleter = void (*)(void* object);
	using ObjectPtr = std::unique_ptr<void, ObjectDeleter>;

	// Visits one entry of a Map in key order: `context` is the caller's pointer, `value` the entry's value.
	using MapEntryVisitor = void (*)(void* context, const std::string& key, const void* value);

	// Type-erased operations on a value of one reflected C++ type, generated by Detail::MakeTypeOps<T>() at registration.
	// Every pointer is null for a schema-only type (one that describes JSON without a C++ object, such as a script field
	// schema, M13); otherwise the ones listed for the type's kind are set. Addresses passed in must point to an object of
	// exactly that C++ type (a programmer error otherwise). Not thread-safe for the same object; main thread for
	// components (§4.11).
	struct TypeOps
	{
		// Every kind.
		ObjectPtr (*Create)() = nullptr;                               // a new default-constructed object
		void (*Copy)(void* destination, const void* source) = nullptr; // copy assignment
		void (*Reset)(void* object) = nullptr;                         // assigns the default value T{}

		// Scalar kinds and Variant (IsScalarFieldType). Write requires a Value of the type's kind; enum values must name an
		// enumerator (the callers validate against the EnumInfo first).
		Value (*Read)(const void* object) = nullptr;
		void (*Write)(void* object, const Value& value) = nullptr;

		// Array and Map.
		size_t (*GetCount)(const void* container) = nullptr;
		void (*Clear)(void* container) = nullptr;

		// Array (std::vector<T>): Resize default-constructs new elements; element addresses are invalidated by Resize and
		// Clear.
		void (*Resize)(void* array, size_t count) = nullptr;
		void* (*GetElement)(void* array, size_t index) = nullptr;
		const void* (*GetConstElement)(const void* array, size_t index) = nullptr;

		// Map (std::map<std::string, T>): entries are visited in std::map (byte-wise) key order. FindOrInsert inserts a
		// default-constructed value when the key is absent. Erase returns whether the key existed.
		void (*VisitEntries)(const void* map, void* context, MapEntryVisitor visitor) = nullptr;
		void* (*FindOrInsert)(void* map, std::string_view key) = nullptr;
		const void* (*Find)(const void* map, std::string_view key) = nullptr;
		bool (*Erase)(void* map, std::string_view key) = nullptr;
	};

	// The description of a reflected value type (Architecture §5.4, "TypeInfo"): its kind, the element type of an Array or
	// Map, the EnumInfo of an Enum, the StructInfo of a Struct, the accepted asset type of an AssetRef, and its type-erased
	// operations. Fields of the same C++ type share one TypeInfo. The TypeRegistry owns the TypeInfos of registered C++
	// types (TypeRegistry::GetOrCreateType); a script field schema owns its schema-only TypeInfos. Immutable after
	// construction; thread-safe.
	class TypeInfo
	{
	public:
		struct Specification
		{
			FieldType Kind = FieldType::Bool;
			// FieldTypeToString(Kind) for scalars and containers; the registry name for enums and structs.
			std::string Name;
			const TypeInfo* Element = nullptr;  // Array and Map
			const EnumInfo* Enum = nullptr;     // Enum
			const StructInfo* Struct = nullptr; // Struct
			std::string AssetTypeName;          // AssetRef: the accepted AssetType name, empty = any
			TypeOps Ops;                        // all null for a schema-only type
			TypeKey Key = nullptr;              // null for a schema-only type
		};

		explicit TypeInfo(Specification specification)
			: m_Specification(std::move(specification))
		{
		}

		[[nodiscard]] FieldType GetKind() const { return m_Specification.Kind; }
		[[nodiscard]] const std::string& GetName() const { return m_Specification.Name; }
		[[nodiscard]] const TypeInfo* GetElement() const { return m_Specification.Element; }
		[[nodiscard]] const EnumInfo* GetEnum() const { return m_Specification.Enum; }
		[[nodiscard]] const StructInfo* GetStruct() const { return m_Specification.Struct; }
		[[nodiscard]] const std::string& GetAssetTypeName() const { return m_Specification.AssetTypeName; }
		[[nodiscard]] const TypeOps& GetOps() const { return m_Specification.Ops; }
		[[nodiscard]] TypeKey GetKey() const { return m_Specification.Key; }
		// False for a schema-only type, which describes JSON but has no C++ storage.
		[[nodiscard]] bool HasOps() const { return m_Specification.Ops.Create != nullptr; }
	private:
		Specification m_Specification;
	};

