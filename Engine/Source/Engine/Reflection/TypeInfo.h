		template<typename T>
		struct StringMapTraits
		{
			static constexpr bool IsStringMap = false;
		};

		template<typename Element, typename Compare, typename Allocator>
		struct StringMapTraits<std::map<std::string, Element, Compare, Allocator>>
		{
			static constexpr bool IsStringMap = true;
			using ElementType = Element;
		};

		// The FieldType a member of C++ type T reflects as (FieldBuilder::Field). Any class type not listed is a Struct,
		// which must be registered before it is used as a field type. bool vectors are rejected: std::vector<bool> has no
		// addressable elements.
		template<typename T>
		[[nodiscard]] consteval FieldType DeduceFieldType()
		{
			if constexpr (std::is_same_v<T, bool>)
				return FieldType::Bool;
			else if constexpr (std::is_same_v<T, int32_t>)
				return FieldType::Int32;
			else if constexpr (std::is_same_v<T, uint32_t>)
				return FieldType::UInt32;
			else if constexpr (std::is_same_v<T, float>)
				return FieldType::Float;
			else if constexpr (std::is_same_v<T, glm::vec2>)
				return FieldType::Vec2;
			else if constexpr (std::is_same_v<T, glm::vec3>)
				return FieldType::Vec3;
			else if constexpr (std::is_same_v<T, glm::vec4>)
				return FieldType::Vec4;
			else if constexpr (std::is_same_v<T, glm::quat>)
				return FieldType::Quat;
			else if constexpr (std::is_same_v<T, glm::bvec3>)
				return FieldType::Bool3;
			else if constexpr (std::is_same_v<T, std::string>)
				return FieldType::String;
			else if constexpr (std::is_same_v<T, UUID>)
				return FieldType::EntityRef;
			else if constexpr (std::is_same_v<T, VariantValue>)
				return FieldType::Variant;
			else if constexpr (AssetFieldTraits<T>::IsAssetField)
				return FieldType::AssetRef;
			else if constexpr (std::is_enum_v<T>)
				return FieldType::Enum;
			else if constexpr (VectorTraits<T>::IsVector)
			{
				static_assert(!std::is_same_v<typename VectorTraits<T>::ElementType, bool>, "std::vector<bool> cannot be reflected");
				return FieldType::Array;
			}
			else if constexpr (StringMapTraits<T>::IsStringMap)
				return FieldType::Map;
			else if constexpr (std::is_class_v<T> && std::is_default_constructible_v<T> && std::is_copy_assignable_v<T>)
				return FieldType::Struct;
			else
				static_assert(sizeof(T) == 0, "this C++ type has no reflected FieldType (see FieldType.h)");
		}

		template<typename T>
		[[nodiscard]] ObjectPtr CreateObject()
		{
			return ObjectPtr(CreateScope<T>().release(), [](void* object)
			{
				std::default_delete<T>()(static_cast<T*>(object));
			});
		}

		// The Value of a scalar or Variant object of C++ type T reflected as `Kind`.
		template<typename T, FieldType Kind>
		[[nodiscard]] Value ReadScalar(const void* object)
		{
			const T& value = *static_cast<const T*>(object);
			if constexpr (Kind == FieldType::Bool)
				return Value::FromBool(value);
			else if constexpr (Kind == FieldType::Int32)
				return Value::FromInt32(value);
			else if constexpr (Kind == FieldType::UInt32)
				return Value::FromUInt32(value);
			else if constexpr (Kind == FieldType::Float)
				return Value::FromFloat(value);
			else if constexpr (Kind == FieldType::Vec2)
				return Value::FromVec2(value);
			else if constexpr (Kind == FieldType::Vec3)
				return Value::FromVec3(value);
			else if constexpr (Kind == FieldType::Vec4)
				return Value::FromVec4(value);
			else if constexpr (Kind == FieldType::Quat)
				return Value::FromQuat(value);
			else if constexpr (Kind == FieldType::Color3)
				return Value::FromColor3(value);
			else if constexpr (Kind == FieldType::Color4)
				return Value::FromColor4(value);
			else if constexpr (Kind == FieldType::Bool3)
				return Value::FromBool3(value);
			else if constexpr (Kind == FieldType::String)
				return Value::FromString(value);
			else if constexpr (Kind == FieldType::EntityRef)
				return Value::FromEntityRef(value);
			else if constexpr (Kind == FieldType::AssetRef)
				return Value::FromAssetRef(AssetFieldTraits<T>::GetHandle(value));
			else if constexpr (Kind == FieldType::Enum)
				return Value::FromEnum(static_cast<int64_t>(std::to_underlying(value)));
			else if constexpr (Kind == FieldType::Variant)
				return Value::FromVariant(value);
			else
				static_assert(sizeof(T) == 0, "ReadScalar needs a scalar or Variant kind");
		}

		// Assigns `value` (of kind `Kind`) to a scalar or Variant object of C++ type T.
		template<typename T, FieldType Kind>
		void WriteScalar(void* object, const Value& value)
		{
			T& target = *static_cast<T*>(object);
			if constexpr (Kind == FieldType::Bool)
				target = value.AsBool();
			else if constexpr (Kind == FieldType::Int32)
				target = value.AsInt32();
			else if constexpr (Kind == FieldType::UInt32)
				target = value.AsUInt32();
			else if constexpr (Kind == FieldType::Float)
				target = value.AsFloat();
			else if constexpr (Kind == FieldType::Vec2)
				target = value.AsVec2();
			else if constexpr (Kind == FieldType::Vec3 || Kind == FieldType::Color3)
				target = value.AsVec3();
			else if constexpr (Kind == FieldType::Vec4 || Kind == FieldType::Color4)
				target = value.AsVec4();
			else if constexpr (Kind == FieldType::Quat)
				target = value.AsQuat();
			else if constexpr (Kind == FieldType::Bool3)
				target = value.AsBool3();
			else if constexpr (Kind == FieldType::String)
				target = value.AsString();
			else if constexpr (Kind == FieldType::EntityRef)
				target = value.AsUUID();
			else if constexpr (Kind == FieldType::AssetRef)
				AssetFieldTraits<T>::SetHandle(target, value.AsUUID());
			else if constexpr (Kind == FieldType::Enum)
				target = static_cast<T>(static_cast<std::underlying_type_t<T>>(value.AsEnum()));
			else if constexpr (Kind == FieldType::Variant)
				target = value.AsVariant();
			else
				static_assert(sizeof(T) == 0, "WriteScalar needs a scalar or Variant kind");
		}

		// The type-erased operations of C++ type T reflected as `Kind` (Kind differs from DeduceFieldType<T>() only for
		// colours).
		template<typename T, FieldType Kind = DeduceFieldType<T>()>
		[[nodiscard]] TypeOps MakeTypeOps()
		{
			TypeOps ops;
			ops.Create = &CreateObject<T>;
			ops.Copy = [](void* destination, const void* source)
			{
				*static_cast<T*>(destination) = *static_cast<const T*>(source);
			};
			ops.Reset = [](void* object)
			{
				*static_cast<T*>(object) = T{};
			};

			if constexpr (IsScalarFieldType(Kind))
			{
				ops.Read = &ReadScalar<T, Kind>;
				ops.Write = &WriteScalar<T, Kind>;
			}
			else if constexpr (Kind == FieldType::Array)
			{
				ops.GetCount = [](const void* container) -> size_t
				{
					return static_cast<const T*>(container)->size();
				};
				ops.Clear = [](void* container)
				{
					static_cast<T*>(container)->clear();
				};
				ops.Resize = [](void* array, size_t count)
				{
					static_cast<T*>(array)->resize(count);
				};
				ops.GetElement = [](void* array, size_t index) -> void*
				{
					return &(*static_cast<T*>(array))[index];
				};
				ops.GetConstElement = [](const void* array, size_t index) -> const void*
				{
					return &(*static_cast<const T*>(array))[index];
				};
			}
			else if constexpr (Kind == FieldType::Map)
			{
				ops.GetCount = [](const void* container) -> size_t
				{
					return static_cast<const T*>(container)->size();
				};
				ops.Clear = [](void* container)
				{
					static_cast<T*>(container)->clear();
				};
				ops.VisitEntries = [](const void* map, void* context, MapEntryVisitor visitor)
				{
					for (const auto& [key, value] : *static_cast<const T*>(map))
						visitor(context, key, &value);
				};
				ops.FindOrInsert = [](void* map, std::string_view key) -> void*
				{
					return &static_cast<T*>(map)->try_emplace(std::string(key)).first->second;
				};
				ops.Find = [](const void* map, std::string_view key) -> const void*
				{
					const T& entries = *static_cast<const T*>(map);
					const auto found = entries.find(std::string(key));
					return found == entries.end() ? nullptr : &found->second;
				};
				ops.Erase = [](void* map, std::string_view key) -> bool
				{
					return static_cast<T*>(map)->erase(std::string(key)) != 0;
				};
			}
			return ops;
		}

