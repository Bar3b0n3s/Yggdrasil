// The exporter (Architecture §7.6, §14.1, §14.2; Roadmap M7, M15): turns the open project into a standalone game folder
// that the Runtime executable runs. Used by project.export (EditorCore/Automation/ExportMethods.h), `Editor --export`
// (EditorCommandLine.h) and Scripts/Export.py. The M7 exporter v0 (Docs/Decisions/0012-m7-decisions.md decision 14) gains
// in M15 (Docs/Decisions/0024-m15-contract.md decisions 3 to 8): testing exports (Testing, TestingExport.h), resource
// patching (PatchResources, ExecutableResources.h, Platform/ResourcePatcher.h), the macOS bundle (AppBundle.h, Sign), the
// notices file, OutputPath, phase timings, and validation of project environments under --renderer none.
//
// The package (§14.1), in OutputDirectory:
//   <Name>(.exe)                 the target configuration's Runtime executable, renamed after the project's Name
//   vcruntime140.dll vcruntime140_1.dll msvcp140.dll   Windows: the app-local CRT from bin/<OutputDir>/Runtime/Redist
//                                (copied there by Scripts/Build.py, §2.3)
//   Game.json                    the manifest (Engine/Project/GameManifest.h): Name, EngineVersion, StartScene, the paks
//                                with their XXH64, Window, Simulation, and Testing (ExportSpecification::Testing); M19
//                                (decision 18, stream D): version 2 with the exporting build's id, Build
//   THIRD_PARTY_NOTICES.txt      M15: copied from bin/<OutputDir>/Runtime/THIRD_PARTY_NOTICES.txt, which Scripts/Build.py
//                                generates from Vendor/*/VENDOR.md and Resources/LICENSES.md (ADR 0024 decision 8)
//   Data/Engine.pak              the target configuration's shaders (every .spv and .refl.json file of
//                                bin/<OutputDir>/Shaders as plain files under "Shaders/", PakFormat.h) and the File and
//                                Generated built-ins of Resources/EngineAssets.json cooked from the engine cooked cache (the
//                                Default font, the Studio and Sky environments, from M8 the blue noise and from M12 the ten
//                                sound-effect presets engine://Audio/*), each baked first when the cache holds no current
//                                bake (the environments with the editor's GPU baker, M8). An editor without a GPU
//                                (--renderer none) whose engine cache holds no bake of a built-in environment leaves that
//                                environment out with a warning and the hint "start the editor with a GPU once to bake
//                                this environment"; step 2 fails when an included asset references it
//                                (Docs/Decisions/0013-m8-decisions.md decision 9). Metadata {"Configuration":
//                                "<Debug|Release|Dist>", "EngineVersion": "..."}. Procedural built-ins (the silent clip of
//                                M12 among them) are generated by the Runtime's asset manager and are not in the pak.
//                                M19 (Docs/Decisions/0030-m19-contract.md decision 20, B-PRUNE-ENG, stream D): of the File
//                                and Generated built-ins, only those the Runtime asks for by handle
//                                (GetRuntimeRequiredBuiltinHandles) and those a packaged asset reaches (step 2's references,
//                                with their own dependencies) are cooked and packaged, or every one of them when a packaged
//                                script computes an Assets.Load reference; ExportReport::Reachability names what was kept
//                                and why, and what was left out. The metadata gains "Build" (decision 13).
//   Data/Game.pak                every registered asset under Assets/ (main assets and sub-assets) except the
//                                Export.Exclude globs, cooked through the editor's asset manager (Library/Cache, §7.5); a
//                                testing export also packages, whatever Export.Exclude says, everything below Assets/Tests/,
//                                every Testing.Suites script and scene and every replay Testing.Replays matches (§7.6,
//                                TestingExport.h). Metadata {"Project": <the canonical ProjectSettings document>} (§14.1:
//                                the project settings, Testing included, ride in the TOC of every export; only Game.json's
//                                Testing admits --feature-test). M19 (decision 21, B-PRUNE-GAME, stream R): with
//                                Export.PruneUnreferenced, only the assets of that set that StartScene and
//                                Export.BuildScenes (and a testing export's forced content) reach through step 2's
//                                references; ExportReport::Reachability says why each one is there and lists the rest.
// Pak version 2 (decision 17, stream G): PakWriter deflates the entries of both paks where that saves at least an eighth.
// macOS (M15, AppBundle.h): the output directory holds only "<Name>.app", and everything above lives in its Contents.
// Paks are written with PakWriter, so equal inputs give byte-identical paks (§7.6, "test_export_is_deterministic"); the
// manifest is written canonically (JsonWriter), so two exports of an unchanged project are identical file for file.
//
// The steps (§14.2), each failing the export with a located error and removing the partial output. Everything is built in
// a staging directory beside OutputDirectory (on the same volume) and reaches OutputDirectory only in step 7, so a failed or
// cancelled export leaves an earlier export there untouched:
//   1. Validate: a project is open; StartScene is set and is a registered scene; every Export.BuildScenes entry and the
//      start scene load strictly (SceneSerializer, LoadOptions Strict); the asset manager has no error diagnostic
//      (EditorAssetManager::HasErrorDiagnostics, §7.2); Name is a valid file name; every script compiles and type-checks
//      (M13); Export.Icon, Version and Company resolve (M14). M15: a testing export also requires valid Testing.Suites and
//      replays that compile (CollectTestingExportContent); and an editor without a graphics device reports every included
//      Environment source that has no current cooked bake as an issue naming the asset, with the GPU hint, instead of
//      failing in step 2 (§14.2 step 1 "validation works under --renderer none, using cooked environment bakes"). A testing
//      export also loads every Testing.Suites scene strictly, since it packages them and the Runtime loads them. Last, the
//      build outputs are located (step 4's NotFound, IsMissingBuildOutput) and the output directory is checked: an existing
//      OutputDirectory must be empty or hold an earlier export (a Game.json that loads as a GameManifest, or on macOS a
//      "<Name>.app" whose Contents/Resources/Game.json does), otherwise the export fails with InvalidArgument naming it and
//      writes nothing; a directory whose status cannot be read is refused too (Io) (M15, ADR 0024 decision 3: an export
//      never replaces a directory that is not a package; the M15 review's M01 made the manifest load the proof).
//   2. Cook every included asset (EditorAssetManager, incrementally from Library/Cache), on jobs. Every asset handle a
//      packaged asset references (scenes, prefabs, materials) must resolve in Game.pak, Engine.pak or the procedural
//      built-ins; one that does not is a Validation error of this step (for a built-in environment left out of Engine.pak,
//      with the hint to bake it once on a GPU). M19 (decisions 19 to 21, stream D): an asset's references are its
//      Import.Dependencies (every importer fills them with every asset it references), plus, for a scene or a prefab, the
//      AssetRef values of its Script components' Fields and of its prefab overrides of Script fields, read with the
//      editor's script field schemas (GetScriptSchemaSnapshot), which an importer does not have; the rule above checks
//      both. A script also reaches the assets its literal Assets.Load calls name (FindScriptAssetLoads,
//      Scripting/ScriptAssetLoads.h) that resolve as Assets.Load resolves them; one that resolves to nothing is no error,
//      since Assets.Load returns nil for it in the editor too. Engine.pak's built-ins and, with Export.PruneUnreferenced,
//      Game.pak follow these references and loads.
//   3. Write Engine.pak and Game.pak atomically into the staging directory, then reopen both (PakReader) and verify every
//      hash.
//   3a. M19 NativeBuild (Docs/Decisions/0030-m19-contract.md decision 33, C-NATIVE-STATIC): a project with a Native/ directory
//      (HasNativeModuleDirectory) gets a Runtime executable that links its module, built by Scripts/BuildNative.py --kind
//      runtime of the target configuration into a directory beside the staging directory (NativeExport.h,
//      StartNativeRuntimeBuild); a build that does not succeed fails the export with CompileFailed and its diagnostics
//      (MakeNativeBuildError). Step 1 refuses such a project first, before anything is cooked: Unsupported on Linux and
//      macOS, PermissionDenied while the user's "Allow native code" preference is off (CheckNativeExport). A project without
//      Native/ skips the step and packages the prebuilt Runtime unchanged.
//   4. Copy the Runtime executable of the target configuration, renamed, and on Windows its Redist/*.dll. A missing binary
//      is NotFound naming "python Scripts/Build.py --config <Config> --project Runtime"; the editor never builds the engine
//      (M19: it builds only a native game's Runtime, step 3a, whose executable this step copies instead). M15: on macOS the
//      bundle's frameworks and ICD manifest, staged by Build.py in Runtime/Frameworks and Runtime/Vulkan/icd.d.
//   4a. M15 PatchResources: Windows patches the copied executable (BuildExecutableResourceSet, ResourcePatcher::Patch);
//      macOS writes Info.plist and, with an icon, AppIcon.icns; Linux has nothing to write. ExportReport::ResourcesPatched.
//   5. Write Game.json and THIRD_PARTY_NOTICES.txt: the staged package is complete.
//   5a. M15 Sign: macOS ad-hoc signs the bundle (codesign, AppBundle.h); nothing elsewhere.
//   6. Optionally run the smoke test (§14.2 step 7) on the staged package: its executable, with Game.json and the paks next
//      to it, with --headless --frames <SmokeTestFrames> --expect-no-errors and, per configuration:
//        - Debug and Release: --user-data-dir <a temporary directory beside the staging directory, never inside the
//          package>, so the run never writes the real profile; and --renderer none when the exporting editor has no
//          graphics device (EngineContext::GetGraphicsDevice: started with --renderer none, or no Vulkan device).
//        - Dist, which honours only §13.9's options: nothing more, so the run writes its log under <UserData>/<Name>/ as the
//          shipped game does. Without a graphics device in the exporting editor it cannot run (a Dist Runtime has no
//          --renderer none and exits 3 without a device): the test is not run, SmokeTestRan stays false and a warning
//          says why.
//      A non-zero exit code fails the export, naming the code and the end of its output.
//   6a. M19 FeatureTest (Docs/Decisions/0030-m19-contract.md decision 10, A-DISTSELF): with ExportSpecification::FeatureTest,
//      which needs Testing, run the staged package's executable by its fixed path with the fixed arguments --headless
//      --feature-test (plus --renderer none for Debug and Release from an editor without a graphics device, as for the
//      smoke test), no argument a request supplies. A testing export keeps its user data inside the package
//      (bin/TestUserData/<Name>/, GetTestingUserDataRoot); the run works there, so its JSON report
//      (bin/TestResults/FeatureTest-<Mode>.json below that folder) moves with the package. Step 6a reads it into ExportReport::FeatureTest: whether the run passed, its exit code, the report's path
//      after the move, and every replay row's path and observed state hash, the hashes a builder compares with the games
//      suite's Dist half. A Dist export from an editor without a graphics device cannot run it (as for the smoke test): it
//      is not run, FeatureTest.Ran stays false and a warning says why. A failed run does not fail the export: the report
//      says so (Passed false, its exit code), so the builder sees which rows failed; a run that cannot start or whose
//      report cannot be read fails the export, naming why.
//   7. Move the staging directory into OutputDirectory, replacing an earlier export there; step 1's output directory rule
//      is checked again first, since the directory may have changed during the cook.
//   8. Return the report, with the time of every phase entered (ExportReport::PhaseTimings; SmokeTest only when it ran).
//
// Main thread only (the asset manager and the open scene are main-thread state, §4.11); the cooking and the smoke test's
// process run in the background, and Poll advances the export once per frame, so the editor stays responsive (§13.2
// "Pending operations"). Not copyable.

namespace Engine {

	class EditorContext;

	// Where an export runs: the steps of the file comment, in order.
	enum class ExportPhase : uint8_t
	{
		Validate,
		Cook,
		WritePaks,
		NativeBuild, // M19 (decision 33): step 3a
		CopyRuntime,
		PatchResources,
		WriteManifest,
		Sign,
		SmokeTest,
		FeatureTest, // M19 (decision 10): step 6a
		MoveToOutput,
		Done
	};

	// How long one phase took (ExportReport::PhaseTimings, §14.2 step 8 "timings").
	struct ExportPhaseTiming
	{
		ExportPhase Phase = ExportPhase::Validate;
		double Seconds = 0.0; // wall-clock, for the report only
	};

	struct ExportSpecification
	{
		ExportConfiguration Configuration = ExportConfiguration::Release;
		// The project-relative output directory, which must lie under "Build/" (§13.2: project.export writes only under
		// <Project>/Build/); empty: GetDefaultOutputDirectory. With ExportRoot, what follows "Build/" goes below the root;
		// ignored when OutputPath is set.
		std::string OutputDirectory{};
		// `Editor --export-root <dir>` (M15, §13.4): an absolute directory that replaces the project's Build/ directory:
		// the export goes to <ExportRoot>/<OutputDirectory without its leading "Build/">, or with an empty OutputDirectory to
		// <ExportRoot>/<Platform>-<Config>[-Testing]/<Name>. Empty: under the project.
		std::filesystem::path ExportRoot{};
		// `Editor --export <dir>` (M15, §12.1): the absolute package directory itself; when set, OutputDirectory and
		// ExportRoot are ignored. Start refuses it (InvalidArgument naming the rule) when it is relative; when it is a
		// file-system root (it has no parent directory); and when it equals, or is an ancestor of, the project's root,
		// BinaryRoot, the process's working directory or the user-data root (Paths::GetUserDataRoot), so a typo such as
		// `--export .` can never replace a source tree or a profile. Its parent must exist or be creatable; an existing
		// directory there is replaced as a whole only when it is empty or holds an earlier export (step 1's output rule).
		std::filesystem::path OutputPath{};
		// The repository's bin directory, where bin/<Config>-<system>-<arch>/Runtime and .../Shaders of the target
		// configuration are (§14.2 step 4). The editor passes <repo>/bin (ENGINE_REPO_ROOT); tests pass the same. Required.
		std::filesystem::path BinaryRoot{};
		// A testing export (§7.6, §14.1, §14.2 step 1; ADR 0024 decision 6): Game.json says "Testing": true; Assets/Tests/**,
		// every Testing.Suites script and scene and every Testing.Replays match are packaged whatever Export.Exclude says; and
		// Validate also refuses invalid suites (TEST_SUITE_INVALID) and replays that do not import (TestingExport.h).
		bool Testing = false;
		// Run step 6's smoke test.
		bool SmokeTest = false;
		// The smoke test's --frames (§14.2: 300).
		uint32_t SmokeTestFrames = 300;
		// M19 (Docs/Decisions/0030-m19-contract.md decision 10, A-DISTSELF): run step 6a's --feature-test of the staged package.
		// Requires Testing: Start refuses it without (InvalidArgument naming the rule).
		bool FeatureTest = false;
	};

	// One replay row of an exported package's --feature-test run (ExportFeatureTestReport::Replays).
	struct ExportFeatureTestReplay
	{
		std::string Path{};      // the replay's project-relative path, as the report's replay:<path> row names it
		std::string StateHash{}; // the observed state hash at its final tick, as the report's FinalStateHash row holds it
		bool Passed = false;     // every row of that replay passed
	};

	// What step 6a found (ExportReport::FeatureTest).
	struct ExportFeatureTestReport
	{
		bool Ran = false;                               // false without ExportSpecification::FeatureTest, and for a Dist export without a device
		int ExitCode = 0;                               // meaningful only when Ran
		bool Passed = false;                            // exit code 0 and every row passed
		std::filesystem::path ReportPath{};             // the JSON report, below OutputDirectory after the move
		std::vector<ExportFeatureTestReplay> Replays{}; // sorted by Path
	};

	// M19 (Docs/Decisions/0030-m19-contract.md decisions 20 and 21): why an asset is in a pak (ExportReachedAsset::Reason).
	enum class ExportReachReason : uint8_t
	{
		StartScene,   // Game.pak: the project's StartScene
		BuildScene,   // Game.pak: an Export.BuildScenes entry
		Testing,      // Game.pak: content a testing export packages whatever Export.Exclude says (TestingExport.h)
		Dependency,   // a reference of From (step 2): its Import.Dependencies or a Script field value, naming it or a sub-asset of it
		LiteralLoad,  // From, a packaged script, loads it by a literal Assets.Load at Line
		Required,     // Engine.pak: the Runtime asks for it by handle (GetRuntimeRequiredBuiltinHandles)
		ComputedLoad, // Engine.pak: kept with every File and Generated built-in, because From computes an Assets.Load at Line
	};

	// One asset of a pak and the first reason the reachability walk found for it (decisions 20 and 21). The walk starts
	// from the roots in order (StartScene, Export.BuildScenes in their order, then a testing export's forced content and
	// the required built-ins, each sorted by path) and follows each reached asset's references in handle order, then a
	// script's literal loads in source order, breadth-first, so the reason is deterministic.
	struct ExportReachedAsset
	{
		std::string Path{}; // the main asset's project path ("Assets/Audio/Beep.sfx") or the built-in's engine path
		ExportReachReason Reason = ExportReachReason::Dependency;
		std::string From{}; // the asset that reached it (Dependency, LiteralLoad, ComputedLoad); empty otherwise
		uint32_t Line = 0;  // 1-based line of From's Assets.Load (LiteralLoad, ComputedLoad); 0 otherwise
	};

	// An Assets.Load whose reference a packaged script computes (FindScriptAssetLoads), which no export can follow.
	struct ExportComputedLoad
	{
		std::string Script{}; // the script's project path
		uint32_t Line = 0;    // 1-based
		uint32_t Column = 0;  // 1-based
	};

	// What the export put into its paks and why (ExportReport::Reachability; decisions 20 and 21).
	struct ExportReachability
	{
		// Export.PruneUnreferenced was on: Game.pak holds only what the walk reached. Off, GameAssets and PrunedAssets are
		// empty and Game.pak holds every asset below Assets/ that Export.Exclude leaves in (GameAssetCount).
		bool Pruned = false;
		std::vector<ExportReachedAsset> GameAssets{};     // every main asset of a pruned Game.pak, sorted by Path
		std::vector<std::string> PrunedAssets{};          // the main assets an unpruned export would have packaged but no root reaches, sorted
		std::vector<ExportReachedAsset> EngineBuiltins{}; // every File and Generated built-in of Engine.pak, sorted by Path
		std::vector<std::string> PrunedBuiltins{};        // the File and Generated built-ins Engine.pak leaves out, sorted
		std::vector<ExportComputedLoad> ComputedLoads{};  // of every packaged script, sorted by (Script, Line, Column)
	};

	// One file of the package.
	struct ExportedFile
	{
		std::string Path{}; // relative to the output directory, forward slashes
		uint64_t Size = 0;
		uint64_t Hash = 0; // XXH64 (seed 0) of the bytes
	};

	// What an export produced (§14.2 step 8).
	struct ExportReport
	{
		std::filesystem::path OutputDirectory{};
		std::filesystem::path Executable{};
		ExportConfiguration Configuration = ExportConfiguration::Release;
		std::vector<ExportedFile> Files{}; // sorted by Path
		uint32_t GameAssetCount = 0;       // cooked entries of Game.pak
		uint32_t EngineEntryCount = 0;     // entries of Engine.pak (shader files and built-ins)
		std::vector<std::string> Warnings{};
		// Whether step 6 ran the exported executable: false without SmokeTest, and for a Dist export from an editor without
		// a graphics device (with a warning).
		bool SmokeTestRan = false;
		int SmokeTestExitCode = 0; // meaningful only when SmokeTestRan (project.export reports null otherwise)
		double Seconds = 0.0;      // wall-clock duration, for the report only
		// M15 (ADR 0024 decisions 2, 4 and 6).
		bool Testing = false;          // ExportSpecification::Testing
		uint32_t TestSuiteCount = 0;   // a testing export's Testing.Suites entries (TestingExportContent::SuiteCount)
		uint32_t ReplayCount = 0;      // a testing export's packaged replays (TestingExportContent::Replays)
		bool ResourcesPatched = false; // step 4a wrote the executable's resources (Windows) or Info.plist (macOS)
		// One entry per phase entered, in phase order from Validate to MoveToOutput, including a phase with nothing to do on
		// this host (Sign outside macOS), whose time is about zero. SmokeTest is listed only when the smoke test ran (M16
		// friction S2-06); otherwise its time, about zero, counts toward MoveToOutput, so the timings still add up. M19:
		// FeatureTest likewise, only when it ran, and NativeBuild only for a game with a native module.
		std::vector<ExportPhaseTiming> PhaseTimings{};
		// M19 (decision 10): step 6a's run.
		ExportFeatureTestReport FeatureTest{};
		// M19 (Docs/Decisions/0030-m19-contract.md decision 33): the package's executable links the project's native module
		// (step 3a built it); false for a game without Native/.
		bool NativeModule = false;
		// M19: what the paks hold and why: Engine.pak's half and ComputedLoads by decision 20 (stream D), Game.pak's half by
		// decision 21 (stream R).
		ExportReachability Reachability{};
	};

	class Exporter
	{
	public:
		// Restricts construction to Start; CreateScope still reaches the constructor.
		class ConstructionKey
		{
			ConstructionKey() = default;
			friend class Exporter;
		};

		// Use Start.
		explicit Exporter(ConstructionKey key);
		// Cancels a running export (as Cancel).
		~Exporter();

		Exporter(const Exporter&) = delete;
		Exporter& operator=(const Exporter&) = delete;

		// Starts exporting `editor`'s open project (a documented back-reference that outlives the exporter). Checks the
		// specification at once: InvalidState without a project or for a read-only project; InvalidArgument for an output
		// directory outside "Build/", an empty BinaryRoot, a ExportRoot that is not absolute, an OutputPath its rules refuse,
		// or SmokeTestFrames of 0. The steps run in Poll.
		[[nodiscard]] static Result<Scope<Exporter>> Start(EditorContext& editor, const ExportSpecification& specification);

		// Advances the export (see the file comment); nullopt while it runs, then the report or the error of the step that
		// failed (with the context "while exporting <step>"). Never called again after it returned a value.
		[[nodiscard]] std::optional<Result<ExportReport>> Poll();

		// Stops the export: terminates a running smoke test, waits for cooking jobs, and removes the staging directory and
		// the smoke test's user-data directory; an earlier export in OutputDirectory stays untouched (the move is the last
		// step). Idempotent.
		void Cancel();

		[[nodiscard]] ExportPhase GetPhase() const;

		// "Build/<Platform>-<Config>/<Name>" (§14.1), with GetPlatformName and ExportConfigurationToString; a testing export
		// goes to "Build/<Platform>-<Config>-Testing/<Name>", so it never replaces the plain export (ADR 0024 decision 6).
		[[nodiscard]] static std::string GetDefaultOutputDirectory(std::string_view projectName, ExportConfiguration configuration,
			bool testing = false);
		// "Windows", "Linux" or "macOS": the host, which is the only platform an export targets (§1.2: no cross-OS export).
		[[nodiscard]] static std::string_view GetPlatformName();
		// The directory of a configuration's build outputs under BinaryRoot: "<Config>-<system>-<arch>" as premake names it
		// (premake5.lua OutputDir: "Release-windows-x86_64", "Dist-linux-x86_64", "Debug-macosx-AARCH64").
		[[nodiscard]] static std::string GetBuildOutputDirectoryName(ExportConfiguration configuration);
		// Whether `error`, an export's failure, is a missing build output of BinaryRoot: step 4's NotFound for the Runtime,
		// its shaders, its Redist DLLs (Windows), its THIRD_PARTY_NOTICES.txt or the bundle's frameworks and ICD manifest
		// (macOS). Those errors, and no other, carry the missing path as ErrorLocation::File and name
		// "python Scripts/Build.py --config <Config> --project Runtime"; `Editor --export` exits 3 for them (§4.1 "required
		// file missing") and 1 for every other export failure, NotFound of a project asset included (M15, ADR 0024 decision 3).
		[[nodiscard]] static bool IsMissingBuildOutput(const Error& error);
	private:
		// The editor, the specification, the phase, the staging directory, the cooking jobs, the smoke test's process and the
		// report being built (Exporter.cpp).
		struct State;
	private:
		Scope<State> m_State;
	};

	// "Validate", "Cook", "WritePaks", "NativeBuild", "CopyRuntime", "PatchResources", "WriteManifest", "Sign", "SmokeTest", "FeatureTest",
	// "MoveToOutput" or "Done".
	[[nodiscard]] std::string_view ExportPhaseToString(ExportPhase phase);

}
