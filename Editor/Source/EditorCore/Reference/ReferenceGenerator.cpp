		// Registry text for Markdown prose: '<' outside code spans is escaped, so "<line>" is never read as an HTML tag.
		static std::string EscapeText(std::string_view text)
		{
			std::string escaped;
			escaped.reserve(text.size());
			bool inCode = false;
			for (const char character : text)
			{
				if (character == '`')
					inCode = !inCode;
				if (character == '<' && !inCode)
					escaped += '\\';
				escaped += character;
			}
			return escaped;
		}

		// `text` for a Markdown table cell: line breaks become spaces and '|' is escaped (GitHub tables split on it even in
		// code spans). Apply EscapeText first to prose.
		static std::string EscapeCell(std::string_view text)
		{
			std::string escaped;
			escaped.reserve(text.size());
			for (const char character : text)
			{
				if (character == '\r')
					continue;
				if (character == '\n')
					escaped += ' ';
				else if (character == '|')
					escaped += "\\|";
				else
					escaped += character;
			}
			return escaped;
		}

		// Prose for a table cell.
		static std::string EscapeProseCell(std::string_view text)
		{
			return EscapeCell(EscapeText(text));
		}

		// `text` as an inline code span, with a backtick fence longer than any run inside it.
		static std::string Code(std::string_view text)
		{
			size_t longest = 0;
			size_t run = 0;
			for (const char character : text)
			{
				run = character == '`' ? run + 1 : 0;
				longest = std::max(longest, run);
			}
			const std::string fence(longest + 1, '`');
			const bool pad = longest > 0 || text.starts_with('`') || text.ends_with('`');
			return pad ? std::format("{} {} {}", fence, text, fence) : std::format("{}{}{}", fence, text, fence);
		}

		// The shortest decimal form; a bound that is a float (registry ranges compare as float, §5.4) prints as that float.
		static std::string FormatNumber(double value)
		{
			if (std::abs(value) <= static_cast<double>(std::numeric_limits<float>::max()))
			{
				const float single = static_cast<float>(value);
				if (static_cast<double>(single) == value)
					return std::format("{}", single);
			}
			return std::format("{}", value);
		}

		static std::string Join(const std::vector<std::string>& parts, std::string_view separator)
		{
			std::string joined;
			for (const std::string& part : parts)
			{
				if (!joined.empty())
					joined += separator;
				joined += part;
			}
			return joined;
		}

		[[nodiscard]] static Result<std::string> MinifiedJson(const Json& value)
		{
			return JsonWriter::Write(value, JsonStyle::Minified);
		}

