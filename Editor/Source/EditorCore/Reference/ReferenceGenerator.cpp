		static Json Described(Json schema, std::string_view description)
		{
			Json result = Json::object();
			result["description"] = std::string(description);
			for (auto member = schema.begin(); member != schema.end(); ++member)
				result[member.key()] = member.value();
			return result;
		}

		static Json SingleValue(const Json& value, std::string_view description)
		{
			return Described(Json{ { "enum", Json::array({ value }) } }, description);
		}

		static Json StringSchema(std::string_view description)
		{
			return Described(Json{ { "type", "string" } }, description);
		}

		static Json HandleSchema(std::string_view description, bool nullable = false)
		{
			Json schema = Json::object();
			schema["type"] = nullable ? Json::array({ "string", "null" }) : Json("string");
			schema["pattern"] = std::string(HandlePattern);
			return Described(std::move(schema), description);
		}

		static Json LowercaseHashSchema(std::string_view description)
		{
			return Described(Json{ { "type", "string" }, { "pattern", std::string(LowercaseHashPattern) } }, description);
		}

		static Json IntegerSchema(std::string_view description, std::optional<uint64_t> minimum, std::optional<uint64_t> maximum)
		{
			Json schema = Json::object();
			schema["type"] = "integer";
			if (minimum.has_value())
				schema["minimum"] = *minimum;
			if (maximum.has_value())
				schema["maximum"] = *maximum;
			return Described(std::move(schema), description);
		}

		static Json EnumSchema(const std::vector<std::string>& values, std::string_view description)
		{
			Json list = Json::array();
			for (const std::string& value : values)
				list.push_back(value);
			return Described(Json{ { "enum", std::move(list) } }, description);
		}

		static Json Vector2Schema(std::string_view description)
		{
			const Json number = Json{ { "type", "number" } };
			return Described(Json{ { "type", "array" }, { "prefixItems", Json::array({ number, number }) }, { "minItems", 2 }, { "maxItems", 2 } }, description);
		}

		static Json ObjectSchema(std::string_view description, Json properties, std::vector<std::string> required, Json additional = false)
		{
			Json schema = Json::object();
			schema["type"] = "object";
			schema["properties"] = std::move(properties);
			if (!required.empty())
			{
				Json list = Json::array();
				for (const std::string& name : required)
					list.push_back(name);
				schema["required"] = std::move(list);
			}
			schema["additionalProperties"] = std::move(additional);
			return Described(std::move(schema), description);
		}

		// The document root: "$schema", "title" and the object schema; "$defs" when `definitions` is not empty.
		static Json DocumentSchema(std::string_view title, std::string_view description, Json properties, std::vector<std::string> required,
			Json definitions = Json::object())
		{
			Json schema = Json::object();
			schema["$schema"] = std::string(JsonSchema::Dialect);
			schema["title"] = std::string(title);
			const Json body = ObjectSchema(description, std::move(properties), std::move(required));
			for (auto member = body.begin(); member != body.end(); ++member)
				schema[member.key()] = member.value();
			if (!definitions.empty())
				schema["$defs"] = std::move(definitions);
			return schema;
		}

		static Json HeaderProperties(std::string_view format, uint32_t version)
		{
			Json properties = Json::object();
			properties["Format"] = SingleValue(Json(std::string(format)), "The file's format name; first key of the file.");
			properties["Version"] = SingleValue(Json(version), "The format version this build writes; older versions are migrated when read.");
			return properties;
		}

		// Adds the object definition of `type` (and of everything it references) to `definitions` under its registry name.
		static void AddStructDefinition(Json& definitions, const StructInfo& type)
		{
			Json schema = JsonSchema::ForStruct(type);
			Json body = Json::object();
			for (auto member = schema.begin(); member != schema.end(); ++member)
			{
				if (member.key() == "$schema" || member.key() == "title")
					continue;
				if (member.key() == "$defs")
				{
					for (auto nested = member->begin(); nested != member->end(); ++nested)
						definitions[nested.key()] = nested.value();
					continue;
				}
				body[member.key()] = member.value();
			}
			definitions[type.GetName()] = std::move(body);
		}

		static Json Reference(std::string_view name)
		{
			return Json{ { "$ref", std::format("#/$defs/{}", name) } };
		}

		// The schema of a document whose body is the reflected struct `type` below its Format/Version header.
		static Json StructDocumentSchema(const StructInfo& type, std::string_view format, uint32_t version, std::string_view description)
		{
			Json schema = JsonSchema::ForStruct(type);
			Json properties = HeaderProperties(format, version);
			const auto body = schema.find("properties");
			if (body != schema.end())
			{
				for (auto member = body->begin(); member != body->end(); ++member)
					properties[member.key()] = member.value();
			}
			const auto definitions = schema.find("$defs");
			return DocumentSchema(format, description, std::move(properties), { "Format", "Version" }, definitions != schema.end() ? *definitions : Json::object());
		}

		static std::vector<std::string> GetAssetTypeNames()
		{
			std::vector<std::string> names;
			for (uint16_t value = 1; AssetTypeToString(static_cast<AssetType>(value)) != "None"; ++value)
				names.emplace_back(AssetTypeToString(static_cast<AssetType>(value)));
			return names;
		}

		// The entity object of scene and prefab files, with every known component's definition from the registry.
		static Json EntityDocumentSchemas(const TypeRegistry& types, Json& definitions)
		{
			Json components = JsonSchema::ForComponents(types);
			const auto componentDefinitions = components.find("$defs");
			if (componentDefinitions != components.end())
			{
				for (auto member = componentDefinitions->begin(); member != componentDefinitions->end(); ++member)
					definitions[member.key()] = member.value();
			}
			const auto componentProperties = components.find("properties");
			Json properties = Json::object();
			properties["ID"] = HandleSchema("The entity's id: 16 hex digits, unique within the file.");
			properties["Name"] = StringSchema("The entity's name.");
			properties["Parent"] = HandleSchema("The parent entity's id, or null for a root.", true);
			properties["Active"] = Described(Json{ { "type", "boolean" } }, "Whether the entity itself is active.");
			properties["Tags"] = Described(Json{ { "type", "array" }, { "items", Json{ { "type", "string" } } } }, "The entity's tags.");
			properties["Components"] = ObjectSchema(
				"The entity's components keyed by registry name; unknown components are preserved on save (§6), so they are allowed.",
				componentProperties != components.end() ? *componentProperties : Json::object(), {}, true);
			return ObjectSchema("One entity: its entity keys, then its components.", std::move(properties), { "ID" });
		}

		static Json EntityFileProperties(std::string_view format)
		{
			Json properties = HeaderProperties(format, Migrations::CurrentVersion);
			properties["Name"] = StringSchema("The document's name.");
			return properties;
		}

