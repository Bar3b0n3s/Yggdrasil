		[[nodiscard]] static Result<std::string> GenerateComponents(const TypeRegistry& types, const ScriptApiRegistry& scripts)
		{
			std::string out = std::format("# Components\n\n{}\n\n", GeneratedNote);
			out += "Every component of the type registry, in canonical component order: the order of a scene file's "
				   "`ComponentVersions` and of the keys under each entity's `Components` (§5.3, §6.2). Defaults are the values of a new "
				   "component, written as the file writes them. Ranges and read-only rules are enforced on every write path: files, the "
				   "inspector, scripts and automation (§5.4). Entity-level components are written as entity keys (`ID`, `Name`, "
				   "`Parent`, `Tags`), never under `Components`. The script members of each component are listed after its fields "
				   "(`ScriptAPI.md` has the full script API).\n\n";

			out += "| Component | Category | Flags | Description |\n|---|---|---|---|\n";
			for (const ComponentInfo* component : types.GetComponents())
			{
				out += std::format("| {} | {} | {} | {} |\n", Code(component->GetName()), EscapeCell(component->GetCategory()),
					DescribeComponentFlags(component->GetFlags()), EscapeProseCell(component->GetDescription()));
			}
			out += "\n";

			std::vector<const StructInfo*> structs;
			std::vector<const EnumInfo*> enums;
			std::set<const void*> seen;
			for (const ComponentInfo* component : types.GetComponents())
			{
				out += std::format("## {}\n\n{}\n\n", component->GetName(), EscapeText(component->GetDescription()));
				const auto names = [](std::span<const ComponentInfo* const> list)
				{
					std::vector<std::string> result;
					for (const ComponentInfo* info : list)
						result.push_back(Code(info->GetName()));
					return result.empty() ? std::string("none") : Join(result, ", ");
				};
				out += std::format("- Category: {}\n- Version: {}\n- Flags: {}\n- Requires: {}\n- Excludes: {}\n\n", component->GetCategory(),
					component->GetVersion(), DescribeComponentFlags(component->GetFlags()), names(component->GetRequires()),
					names(component->GetExcludes()));
				ENGINE_TRY(AppendFieldTable(out, *component));
				for (const Scope<FieldInfo>& field : component->GetFields())
					CollectReferencedTypes(field->GetType(), structs, enums, seen);

				const auto group = std::ranges::find(scripts.GetTypes(), component->GetName(), &ScriptApiGroup::Name);
				if (group != scripts.GetTypes().end() && !group->Members.empty())
				{
					out += std::format("Script members of `{}`:\n\n| Member | Kind | Signature | Access | Modes | Description |\n|---|---|---|---|---|---|\n",
						component->GetName());
					for (const ScriptApiMember& member : group->Members)
					{
						std::string access;
						if (member.Kind == ScriptApiMemberKind::Property || member.Kind == ScriptApiMemberKind::ProxyField)
							access = member.Writable ? "read/write" : "read";
						out += std::format("| {} | {} | {} | {} | {} | {} |\n", Code(member.Name), DescribeMemberKind(member.Kind),
							EscapeCell(Code(member.Signature)), access, DescribeModes(member.Options.Modes), EscapeProseCell(member.Description));
					}
					out += "\n";
				}
			}

			std::ranges::sort(structs, {}, &StructInfo::GetName);
			std::ranges::sort(enums, {}, &EnumInfo::GetName);
			if (!structs.empty())
			{
				out += "## Structs\n\nThe structs component fields hold, in name order.\n\n";
				for (const StructInfo* type : structs)
				{
					out += std::format("### {}\n\n{}\n\n", type->GetName(), EscapeText(type->GetDescription()));
					ENGINE_TRY(AppendFieldTable(out, *type));
				}
			}
			if (!enums.empty())
			{
				out += "## Enums\n\nThe enums component fields use, in name order; files spell each value exactly as listed.\n\n";
				for (const EnumInfo* enumeration : enums)
				{
					out += std::format("### {}\n\n{}\n\n| Value | Description |\n|---|---|\n", enumeration->GetName(), EscapeText(enumeration->GetDescription()));
					for (const EnumEntry& entry : enumeration->GetEntries())
						out += std::format("| {} | {} |\n", Code(entry.Name), EscapeProseCell(entry.Description));
					out += "\n";
				}
			}
			return out;
		}

