"""Scripts/Build.py's decision to copy the app-local CRT (Docs/Architecture.md §2.3; Docs/Decisions/0012-m7-decisions.md
decisions 14 and 22): every build that builds the Runtime, directly or as a dependency, copies it next to the Runtime,
where project.export takes it from; a build that does not build the Runtime copies nothing. From M15 (Docs/Decisions/
0024-m15-contract.md, stream A owns this file) the same builds also stage the notices file and, on macOS, the bundle's
SDK files, and a Dist build archives the Runtime's symbols. From M19 (Docs/Decisions/0030-m19-contract.md decision 13,
stream D) every build first writes the build stamp of its configuration.

The solution is a small .slnx written into a temporary directory with the shape premake writes (the Tests project
depends on Runtime through a BuildDependency, Editor links EditorCore through a ProjectReference), so the test runs on
every system and needs no generated workspace.
"""

from __future__ import annotations

import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from harness import REPOSITORY_ROOT

sys.path.insert(0, str(REPOSITORY_ROOT / "Scripts"))

import Build  # noqa: E402  (Scripts/ is on sys.path above; Build imports its Lib package from there)
from Lib import notices, paths, toolchain, workspace  # noqa: E402

SOLUTION = """<Solution Description="Visual Studio slnx file generated by Premake" Version="1.4">
  <Configurations>
    <BuildType Name="Debug" />
    <BuildType Name="Dist" />
    <Platform Name="x64" />
  </Configurations>
  <Project Path="Runtime\\Runtime.vcxproj" />
  <Project Path="Tests\\Tests.vcxproj">
    <Build Solution="Debug|x64" Project="true" />
    <Build Project="false" />
    <BuildDependency Project="Runtime\\Runtime.vcxproj" />
  </Project>
  <Project Path="Editor\\Editor.vcxproj">
    <Build Solution="Debug|x64" Project="true" />
    <Build Project="false" />
  </Project>
  <Folder Name="/Engine/">
    <Project Path="Engine\\Engine.vcxproj" />
    <Project Path="EditorCore\\EditorCore.vcxproj">
      <Build Solution="Debug|x64" Project="true" />
      <Build Project="false" />
    </Project>
  </Folder>
</Solution>
"""

# Each project file with the ProjectReference items of premake's links.
PROJECT_REFERENCES = {
    "Runtime": ["..\\Engine\\Engine.vcxproj"],
    "Tests": ["..\\EditorCore\\EditorCore.vcxproj", "..\\Engine\\Engine.vcxproj"],
    "Editor": ["..\\EditorCore\\EditorCore.vcxproj"],
    "Engine": [],
    "EditorCore": ["..\\Engine\\Engine.vcxproj"],
}


class BuildScriptTests(unittest.TestCase):
    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory(prefix="EngineBuildScript")
        self.addCleanup(temporary.cleanup)
        root = Path(temporary.name)
        (root / "Workspace.slnx").write_text(SOLUTION, encoding="utf-8")
        for project, references in PROJECT_REFERENCES.items():
            items = "".join(f'    <ProjectReference Include="{reference}" />\n' for reference in references)
            text = (f'<Project DefaultTargets="Build">\n  <PropertyGroup>\n    <ConfigurationType>Application'
                    f'</ConfigurationType>\n  </PropertyGroup>\n  <ItemGroup>\n{items}  </ItemGroup>\n</Project>\n')
            (root / project).mkdir()
            (root / project / f"{project}.vcxproj").write_text(text, encoding="utf-8")
        self.solution = workspace.read_solution(root / "Workspace.slnx")

    def test_dependencies_come_from_build_dependencies_and_project_references(self) -> None:
        self.assertEqual(self.solution.dependencies["Tests"], {"Runtime", "EditorCore", "Engine"})
        self.assertEqual(self.solution.dependencies["Editor"], {"EditorCore"})
        self.assertEqual(self.solution.builds_with("Tests"), {"Tests", "Runtime", "EditorCore", "Engine"})
        self.assertEqual(self.solution.builds_with("Editor"), {"Editor", "EditorCore", "Engine"})

    def test_builds_that_build_the_runtime_copy_the_crt(self) -> None:
        # The whole configuration, the Runtime itself and Tests, which depends on it.
        self.assertTrue(Build.builds_runtime(self.solution, "Debug", None))
        self.assertTrue(Build.builds_runtime(self.solution, "Debug", "Runtime"))
        self.assertTrue(Build.builds_runtime(self.solution, "Debug", "Tests"))
        self.assertTrue(Build.builds_runtime(self.solution, "Dist", None))

    def test_builds_without_the_runtime_copy_nothing(self) -> None:
        self.assertFalse(Build.builds_runtime(self.solution, "Debug", "Editor"))
        self.assertFalse(Build.builds_runtime(self.solution, "Debug", "EditorCore"))
        self.assertFalse(Build.builds_runtime(self.solution, "Debug", "Engine"))

    def test_runtime_staging_follows_the_builds_that_build_the_runtime(self) -> None:
        # M15 (Docs/Decisions/0024-m15-contract.md decision 8): the notices and the other staged files follow the same
        # rule as the CRT where the workspace records dependencies; make and ninja record none, so there the Runtime
        # executable written during the build decides.
        root = self.solution.path.parent
        self.assertTrue(Build.builds_runtime_in(self.solution, "Debug", None, 0.0, root))
        self.assertTrue(Build.builds_runtime_in(self.solution, "Debug", "Tests", 0.0, root))
        self.assertFalse(Build.builds_runtime_in(self.solution, "Debug", "Editor", 0.0, root))
        makefiles = workspace.Makefiles("gmake", root / "Makefile", ["Runtime", "Tests", "Engine"],
                                        {"Debug": ["Runtime", "Tests", "Engine"], "Dist": ["Engine"]})
        executable = Build.runtime_output(root, "Debug") / paths.executable_name("Runtime")
        self.assertFalse(Build.builds_runtime_in(makefiles, "Debug", "Tests", 0.0, root))  # no Runtime built at all
        executable.parent.mkdir(parents=True)
        executable.write_bytes(b"runtime")
        os.utime(executable, (1000.0, 1000.0))
        self.assertTrue(Build.builds_runtime_in(makefiles, "Debug", "Tests", 900.0, root))
        self.assertFalse(Build.builds_runtime_in(makefiles, "Debug", "Engine", 1100.0, root))
        self.assertTrue(Build.builds_runtime_in(makefiles, "Debug", "Runtime", 1100.0, root))
        self.assertFalse(Build.builds_runtime_in(makefiles, "Dist", None, 0.0, root))


class RuntimeStagingTests(unittest.TestCase):
    """What Build.py stages beside the Runtime from M15 (Docs/Decisions/0024-m15-contract.md decisions 2, 5 and 8,
    stream A), with the helper names the contract freezes: the notices file after every build that builds the Runtime,
    the Dist Runtime's symbols in bin/Symbols, and the macOS bundle's SDK files. Each helper is host-independent file
    work, so these tests run on every system against temporary directories."""

    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory(prefix="EngineRuntimeStaging")
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)

    def test_the_notices_file_is_generated_next_to_the_runtime(self) -> None:
        result = Build.stage_runtime_notices(self.root, "Release", "windows")
        target = self.root / "bin" / paths.output_directory_name("Release") / "Runtime" / notices.NOTICES_FILE_NAME
        self.assertEqual(Path(result["path"]), target)
        self.assertEqual(target.read_text(encoding="utf-8"), notices.generate_notices(REPOSITORY_ROOT, "windows"))

    def test_a_malformed_notices_section_fails_the_build_step_naming_the_file(self) -> None:
        step = Build.Step("build Release", Build.Status.PASSED, "16 project(s) built")
        broken = ValueError("Vendor/Example/VENDOR.md: no '## Notices' section")
        with mock.patch.object(Build.notices, "generate_notices", side_effect=broken):
            Build.stage_runtime_outputs(step, self.root, "Release", paths.Host("windows", "x86_64", "x86_64"))
        self.assertTrue(step.failed)
        self.assertIn("Vendor/Example/VENDOR.md", step.detail)
        healthy = Build.Step("build Release", Build.Status.PASSED, "16 project(s) built")
        Build.stage_runtime_outputs(healthy, self.root, "Release", paths.Host("windows", "x86_64", "x86_64"))
        self.assertFalse(healthy.failed)
        self.assertTrue(Path(str(healthy.data["notices"]["path"])).is_file())

    def test_dist_symbols_are_archived_and_never_beside_the_shipped_files(self) -> None:
        runtime = self.root / "bin" / paths.output_directory_name("Dist") / "Runtime"
        runtime.mkdir(parents=True)
        (runtime / "Runtime.map").write_text("map", encoding="utf-8")
        (runtime / "Runtime.pdb").write_bytes(b"pdb")
        result = Build.archive_dist_symbols(self.root)
        archive = self.root / "bin" / "Symbols" / paths.output_directory_name("Dist") / "Runtime"
        self.assertEqual(Path(result["destination"]), archive)
        self.assertEqual((archive / "Runtime.map").read_text(encoding="utf-8"), "map")
        (runtime / "Runtime.map").unlink()
        with self.assertRaises(FileNotFoundError):
            Build.archive_dist_symbols(self.root)

    def test_the_macos_sdk_files_are_staged_from_the_pinned_sdk_only(self) -> None:
        sdk = self.root / "VulkanSDK"
        pinned = toolchain.load_pins().vulkan_sdk_version.split(".")
        header = sdk / "include" / "vulkan" / "vulkan_core.h"
        header.parent.mkdir(parents=True)
        header.write_text(f"#define VK_HEADER_VERSION {pinned[2]}\n#define VK_HEADER_VERSION_COMPLETE "
                          f"VK_MAKE_API_VERSION(0, {pinned[0]}, {pinned[1]}, VK_HEADER_VERSION)\n", encoding="utf-8")
        (sdk / "lib").mkdir()
        (sdk / "lib" / "libvulkan.1.dylib").write_bytes(b"loader")
        (sdk / "lib" / "libMoltenVK.dylib").write_bytes(b"driver")
        (sdk / "share" / "vulkan" / "icd.d").mkdir(parents=True)
        (sdk / "share" / "vulkan" / "icd.d" / "MoltenVK_icd.json").write_text("{}", encoding="utf-8")
        result = Build.stage_macos_frameworks(self.root, "Release", sdk)
        runtime = self.root / "bin" / paths.output_directory_name("Release") / "Runtime"
        self.assertEqual((runtime / "Frameworks" / "libvulkan.1.dylib").read_bytes(), b"loader")
        self.assertEqual((runtime / "Frameworks" / "libMoltenVK.dylib").read_bytes(), b"driver")
        self.assertTrue((runtime / "Vulkan" / "icd.d" / "MoltenVK_icd.json").is_file())
        self.assertEqual(len(result["files"]), 3)
        self.assertTrue(all(len(entry["sha256"]) == 64 for entry in result["files"]))
        header.write_text("#define VK_HEADER_VERSION 1\n#define VK_HEADER_VERSION_COMPLETE "
                          "VK_MAKE_API_VERSION(0, 1, 3, VK_HEADER_VERSION)\n", encoding="utf-8")
        with self.assertRaises(toolchain.ToolchainError):
            Build.stage_macos_frameworks(self.root, "Release", sdk)


class BuildStampTests(unittest.TestCase):
    """The build stamp Build.py writes before each configuration's build (Docs/Decisions/0030-m19-contract.md decision
    13, B-BVER, stream D): the commit a working tree has checked out and whether it differs from it, in the header below
    the Engine project's intermediate directory that Core/BuildId.cpp reads. Each test makes its own repository in a
    temporary directory, with git's search stopped above it."""

    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory(prefix="EngineBuildStamp")
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name).resolve()
        ceiling = mock.patch.dict(os.environ, {"GIT_CEILING_DIRECTORIES": str(self.root)})
        ceiling.start()
        self.addCleanup(ceiling.stop)

    def git(self, repository: Path, *arguments: str) -> str:
        completed = subprocess.run(["git", "-C", str(repository), "-c", "user.name=Engine Tests",
                                    "-c", "user.email=engine-tests@localhost", "-c", "core.autocrlf=false",
                                    "-c", "commit.gpgsign=false", *arguments],
                                   stdin=subprocess.DEVNULL, capture_output=True, text=True, check=True)
        return completed.stdout

    def make_repository(self) -> Path:
        repository = self.root / "Checkout"
        (repository / "Engine" / "Source").mkdir(parents=True)
        (repository / "Engine" / "Source" / "Core.cpp").write_text("int core;\n", encoding="utf-8")
        (repository / ".gitignore").write_text("/bin-int/\nEngine/Generated/\n", encoding="utf-8")
        self.git(repository, "init", "--quiet")
        self.git(repository, "add", "--all")
        self.git(repository, "commit", "--quiet", "-m", "First")
        return repository

    def test_the_stamp_names_head_and_the_changes_that_make_a_build_dirty(self) -> None:
        repository = self.make_repository()
        head = self.git(repository, "rev-parse", "HEAD").strip()
        clean = Build.read_build_stamp(repository)
        self.assertEqual(clean, Build.BuildStamp(head[:12], False))
        self.assertEqual(clean.describe(), head[:12])

        source = repository / "Engine" / "Source" / "Core.cpp"
        source.write_text("int core = 1;\n", encoding="utf-8")
        self.assertTrue(Build.read_build_stamp(repository).dirty)  # a modified tracked file
        self.git(repository, "add", "--all")
        self.assertTrue(Build.read_build_stamp(repository).dirty)  # staged
        self.git(repository, "checkout", "--quiet", "HEAD", "--", ".")
        self.assertEqual(Build.read_build_stamp(repository), clean)

        # A source premake compiles although git does not track it, and a resource the build copies, make it dirty; an
        # untracked file outside those directories and an ignored one do not.
        for directory in Build.BUILD_STAMP_SOURCE_DIRECTORIES:
            with self.subTest(directory=directory):
                added = repository / directory / "Added.cpp"
                added.parent.mkdir(parents=True, exist_ok=True)
                added.write_text("int added;\n", encoding="utf-8")
                stamp = Build.read_build_stamp(repository)
                self.assertEqual(stamp, Build.BuildStamp(head[:12], True))
                self.assertEqual(stamp.describe(), f"{head[:12]}.dirty")
                added.unlink()
        (repository / "Notes.txt").write_text("notes\n", encoding="utf-8")
        (repository / "Engine" / "Generated").mkdir()
        (repository / "Engine" / "Generated" / "Stamp.h").write_text("#pragma once\n", encoding="utf-8")
        self.assertEqual(Build.read_build_stamp(repository), clean)

    def test_without_a_repository_the_stamp_has_no_commit_and_is_clean(self) -> None:
        directory = self.root / "Unversioned"
        (directory / "Engine").mkdir(parents=True)
        (directory / "Engine" / "Core.cpp").write_text("int core;\n", encoding="utf-8")
        stamp = Build.read_build_stamp(directory)
        self.assertEqual(stamp, Build.BuildStamp("", False))
        self.assertEqual(stamp.describe(), "no commit")
        self.assertIn('#define ENGINE_BUILD_COMMIT ""\n', Build.build_stamp_text(stamp))

    def test_the_stamp_header_is_written_per_configuration_and_only_when_it_changes(self) -> None:
        repository = self.make_repository()
        head = self.git(repository, "rev-parse", "HEAD").strip()
        workspace_root = self.root / "Workspace"
        first = Build.write_build_stamp(workspace_root, "Release", repository)
        header = workspace_root / "bin-int" / paths.output_directory_name("Release") / "Engine" / "BuildStamp.h"
        self.assertEqual(Path(str(first["path"])), header)
        self.assertTrue(first["written"])
        self.assertEqual((first["commit"], first["dirty"], first["description"]), (head[:12], False, head[:12]))
        text = header.read_text(encoding="utf-8")
        self.assertIn(f'#define ENGINE_BUILD_COMMIT "{head[:12]}"\n', text)
        self.assertIn("#define ENGINE_BUILD_DIRTY 0\n", text)
        self.assertFalse(Build.write_build_stamp(workspace_root, "Release", repository)["written"])
        self.assertFalse((workspace_root / "bin-int" / paths.output_directory_name("Debug")).exists())

        (repository / "Engine" / "Source" / "Core.cpp").write_text("int core = 2;\n", encoding="utf-8")
        dirty = Build.write_build_stamp(workspace_root, "Release", repository)
        self.assertTrue(dirty["written"])
        self.assertIn("#define ENGINE_BUILD_DIRTY 1\n", header.read_text(encoding="utf-8"))

    def test_a_first_stamp_removes_the_objects_a_build_without_one_compiled(self) -> None:
        # A build without the stamp (the IDE's, before any Build.py run) compiled BuildId.cpp without reading the
        # header, so no incremental build would recompile it: the first stamp removes its objects, and a rewrite keeps
        # them.
        repository = self.make_repository()
        workspace_root = self.root / "Workspace"
        intermediate = workspace_root / "bin-int" / paths.output_directory_name("Debug") / "Engine"
        intermediate.mkdir(parents=True)
        objects = [intermediate / name for name in Build.BUILD_STAMP_OBJECTS]
        for stale in objects:
            stale.write_bytes(b"object")
        (intermediate / "Other.obj").write_bytes(b"object")
        first = Build.write_build_stamp(workspace_root, "Debug", repository)
        self.assertEqual(sorted(first["removedObjects"]), sorted(str(stale) for stale in objects))
        self.assertFalse(any(stale.exists() for stale in objects))
        self.assertTrue((intermediate / "Other.obj").is_file())

        for stale in objects:
            stale.write_bytes(b"object")
        (repository / "Engine" / "Source" / "Core.cpp").write_text("int core = 3;\n", encoding="utf-8")
        rewritten = Build.write_build_stamp(workspace_root, "Debug", repository)
        self.assertTrue(rewritten["written"])
        self.assertEqual(rewritten["removedObjects"], [])
        self.assertTrue(all(stale.is_file() for stale in objects))


