class SourceStampTests(unittest.TestCase):
    """The source stamps Build.py takes as each build begins (refresh_source_stamps; Docs/Architecture.md §2.3, the
    stale Tests.exe of phase 5): the builds compile what is newer than its objects, so a source put back with its older
    modification time (the kept copy of a fix restored after proving that a regression test fails without it) was never
    compiled again, and Build.py reported Tests built while it ran the code the copy had replaced. Every modification
    time below is set explicitly, relative to the record's own time, so no outcome depends on the clock's resolution."""

    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory(prefix="EngineSourceStamps")
        self.addCleanup(temporary.cleanup)
        self.repository = Path(temporary.name).resolve() / "Checkout"
        self.workspace = Path(temporary.name).resolve() / "Workspace"
        self.source = self.write("Editor/Source/EditorCore/Commands/Command.cpp", b"int Fixed() { return 1; }\n",
                                 modified=WRITTEN)
        self.header = self.write("Resources/Shaders/Shared.h", b"#pragma once\n#define SHARED 1\n", modified=WRITTEN)
        self.write("Docs/Example.cpp", b"int notCompiled;\n", modified=WRITTEN)
        self.write("Engine/Source/Engine/Notes.txt", b"not a source\n", modified=WRITTEN)

    def write(self, name: str, data: bytes, modified: int | None = None) -> Path:
        path = self.repository / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        if modified is not None:
            os.utime(path, ns=(modified, modified))
        return path

    def refresh(self) -> tuple[Build.SourceStamps, int]:
        """A build's refresh, and the time its record was taken."""
        stamps = Build.refresh_source_stamps(self.workspace, self.repository)
        record = json.loads(stamps.path.read_bytes().decode("utf-8"))
        return stamps, record["taken"]

    def test_a_source_put_back_with_its_older_time_is_given_the_current_one(self) -> None:
        original = self.source.read_bytes()
        kept = self.source.stat().st_mtime_ns
        first, taken = self.refresh()
        self.assertEqual(first.touched, [], "a first record touches nothing")
        self.assertEqual(first.path, self.workspace / "bin-int" / Build.SOURCE_STAMPS_FILE_NAME)
        self.assertEqual(first.files, 2, "only the C and C++ files of the directories the builds compile")
        # The fix is reverted (an edit, newer than the build that recorded it), and a build compiles the reverted code.
        self.write(self.source.relative_to(self.repository).as_posix(), b"int Fixed() { return 0; }\n",
                   modified=taken + 1_000_000_000)
        reverted, taken = self.refresh()
        self.assertEqual(reverted.touched, [], "an edit newer than the last build's start is the build's to compile")
        # The kept copy is put back with its own, older time: no build would compile it again.
        self.write(self.source.relative_to(self.repository).as_posix(), original, modified=kept)
        restored, _ = self.refresh()
        self.assertEqual(restored.touched, ["Editor/Source/EditorCore/Commands/Command.cpp"])
        self.assertGreater(self.source.stat().st_mtime_ns, taken,
                           "newer than every object the builds compiled before this build began")
        self.assertEqual(self.source.read_bytes(), original, "only the time changes")
        again, _ = self.refresh()
        self.assertEqual(again.touched, [], "a touched source is touched once")

    def test_a_header_put_back_with_its_older_time_is_touched_too(self) -> None:
        original = self.header.read_bytes()
        kept = self.header.stat().st_mtime_ns
        _, taken = self.refresh()
        self.write("Resources/Shaders/Shared.h", b"#pragma once\n#define SHARED 0\n", modified=taken + 1_000_000_000)
        self.refresh()
        self.write("Resources/Shaders/Shared.h", original, modified=kept)
        restored, _ = self.refresh()
        self.assertEqual(restored.touched, ["Resources/Shaders/Shared.h"])

    def test_an_unchanged_source_is_neither_read_nor_touched(self) -> None:
        first, _ = self.refresh()
        self.assertEqual(first.hashed, 2)
        with mock.patch.object(Build, "file_sha256", side_effect=AssertionError("an unchanged file was read")):
            unchanged, _ = self.refresh()
        self.assertEqual((unchanged.hashed, unchanged.touched), (0, []))
        # The same content written again with an older time is the same code: nothing to compile again.
        content = self.source.read_bytes()
        self.write(self.source.relative_to(self.repository).as_posix(), content, modified=1_000_000_000)
        same, _ = self.refresh()
        self.assertEqual((same.hashed, same.touched), (1, []))

    def test_a_source_removed_while_the_stamps_are_taken_is_left_out(self) -> None:
        # An editor that saves through a rename removes the file for a moment: the build goes on without its stamp.
        real = Build.file_sha256

        def vanished(path: Path) -> str:
            if path == self.header:
                raise FileNotFoundError(path)
            return real(path)

        with mock.patch.object(Build, "file_sha256", vanished):
            stamps, _ = self.refresh()
        self.assertEqual((stamps.files, stamps.touched), (1, []))
        self.assertEqual(Build.read_source_stamps(stamps.path)[1].keys(),
                         {"Editor/Source/EditorCore/Commands/Command.cpp"})

    def test_an_unreadable_record_is_written_again_and_touches_nothing(self) -> None:
        record = self.workspace / "bin-int" / Build.SOURCE_STAMPS_FILE_NAME
        record.parent.mkdir(parents=True)
        record.write_bytes(b"{not json")
        first, _ = self.refresh()
        self.assertEqual((first.files, first.touched), (2, []))
        self.assertEqual(Build.read_source_stamps(record)[1].keys(),
                         {"Editor/Source/EditorCore/Commands/Command.cpp", "Resources/Shaders/Shared.h"})


if __name__ == "__main__":
    unittest.main()
