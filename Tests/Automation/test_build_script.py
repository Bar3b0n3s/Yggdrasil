class StaleLinkTests(unittest.TestCase):
    """The guard after an MSBuild build (stale_links, relink; the stale Tests.exe of phase 5, which did not reproduce
    in the setup's attempts): an executable older than a first-party static library it links, after a build that
    succeeded, is one whose link MSBuild skipped although the library changed, so Build.py removes it and builds again
    (a full link). The projects are written with premake's shape (the MSBuild namespace, the configuration's
    conditions, OutDir from $(ProjectDir)); every time is set explicitly."""

    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory(prefix="EngineStaleLinks")
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name).resolve()
        (self.root / "Workspace.slnx").write_text(STALE_LINK_SOLUTION, encoding="utf-8")
        output = paths.output_directory_name("Debug")
        condition = "'$(Configuration)|$(Platform)'=='Debug|x64'"
        self.outputs: dict[str, Path] = {}
        for name, (directory, kind, references) in STALE_LINK_PROJECTS.items():
            up = "..\\" * len(Path(directory).parts)
            extension = ".exe" if kind == "Application" else ".lib"
            items = "".join(f'    <ProjectReference Include="{reference}" />\n' for reference in references)
            text = (f'<?xml version="1.0" encoding="utf-8"?>\n'
                    f'<Project DefaultTargets="Build" xmlns="{vendor_cache.MSBUILD_NAMESPACE}">\n'
                    f'  <PropertyGroup Condition="{condition}" Label="Configuration">\n'
                    f'    <ConfigurationType>{kind}</ConfigurationType>\n  </PropertyGroup>\n'
                    f'  <PropertyGroup Condition="{condition}">\n'
                    f'    <OutDir>$(ProjectDir){up}bin\\{output}\\{name}\\</OutDir>\n'
                    f'    <TargetName>{name}</TargetName>\n    <TargetExt>{extension}</TargetExt>\n'
                    f'  </PropertyGroup>\n  <ItemGroup>\n{items}  </ItemGroup>\n</Project>\n')
            (self.root / directory).mkdir(parents=True)
            (self.root / directory / f"{name}.vcxproj").write_text(text, encoding="utf-8")
            self.outputs[name] = self.root / "bin" / output / name / f"{name}{extension}"
            self.outputs[name].parent.mkdir(parents=True)
        self.solution = workspace.read_solution(self.root / "Workspace.slnx")
        # Tests was linked after every library it links changed, the vendored one included.
        for name, seconds in (("Engine", 900), ("EditorCore", 950), ("ImGui", 990), ("Tests", 1000)):
            self.set_output(name, seconds)

    def set_output(self, name: str, seconds: int, data: bytes = b"built") -> None:
        self.outputs[name].write_bytes(data)
        os.utime(self.outputs[name], ns=(seconds * 10**9, seconds * 10**9))

    def stale(self, project: str | None = "Tests") -> list[tuple[str, str]]:
        return [(link.output.name, link.library.name) for link in Build.stale_links(self.solution, "Debug", project)]

    def test_an_output_older_than_a_first_party_library_it_links_is_a_stale_link(self) -> None:
        self.assertEqual(self.stale(), [])
        self.set_output("EditorCore", 1100)
        self.assertEqual(self.stale(), [("Tests.exe", "EditorCore.lib")])
        self.assertEqual(self.stale(None), [("Tests.exe", "EditorCore.lib")], "a build of every project")
        self.assertEqual(self.stale("EditorCore"), [], "a build that links nothing")
        self.set_output("Engine", 1200)
        self.assertEqual(self.stale(), [("Tests.exe", "EditorCore.lib"), ("Tests.exe", "Engine.lib")])

    def test_a_vendored_library_and_a_missing_output_are_not_compared(self) -> None:
        # The vendored libraries come from the vendor cache, where a library in the workspace may be an older build's.
        self.set_output("ImGui", 2000)
        self.assertEqual(self.stale(), [])
        self.set_output("EditorCore", 1100)
        self.outputs["Tests"].unlink()
        self.assertEqual(self.stale(), [], "no output: MSBuild links it")

    def relinked(self, outcome: str) -> tuple[Build.Step, list[str]]:
        """A build step that succeeded, its stale link and a relink whose build `outcome` is "links" (it writes the
        output again, newer than its libraries), "skips" (it leaves the output out) or "fails"."""
        self.set_output("EditorCore", 1100)
        step = Build.Step("build Debug Tests", Status.PASSED, "Tests built, 0 warnings")
        builds: list[str] = []

        def build() -> tuple[ProcessResult, list[str], list[str]]:
            builds.append("again")
            self.assertFalse(self.outputs["Tests"].exists(), "the stale output is removed first")
            if outcome == "links":
                self.set_output("Tests", 1200, b"relinked")
            elif outcome == "skips":
                self.set_output("Tests", 1000, b"stale")
            failed = outcome == "fails"
            return (ProcessResult(["msbuild"], 1 if failed else 0, False, 1.0, ""), [],
                    ["LINK : fatal error LNK1104"] if failed else [])

        arguments = mock.Mock(allow_warnings=False, allow_vendor_warnings=False)
        Build.relink(step, Build.stale_links(self.solution, "Debug", "Tests"), build,
                     lambda: Build.stale_links(self.solution, "Debug", "Tests"), self.root, arguments,
                     mock.Mock())
        return step, builds

    def test_a_stale_link_is_linked_again_and_the_build_warns_naming_it(self) -> None:
        step, builds = self.relinked("links")
        self.assertEqual(builds, ["again"])
        self.assertEqual(step.status, Status.WARNING)
        self.assertIn("Tests.exe is older than", step.detail)
        self.assertEqual(self.outputs["Tests"].read_bytes(), b"relinked")
        self.assertEqual([Path(entry["library"]).name for entry in step.data["staleLinks"]], ["EditorCore.lib"])

    def test_a_relink_that_fails_or_leaves_the_output_stale_fails_the_build(self) -> None:
        for outcome in ("skips", "fails"):
            with self.subTest(outcome=outcome):
                step, builds = self.relinked(outcome)
                self.assertEqual(builds, ["again"])
                self.assertEqual(step.status, Status.FAILED)
                self.assertIn("relinking the stale links", step.detail)

    def test_an_output_that_cannot_be_removed_fails_the_build(self) -> None:
        # A running Tests.exe cannot be removed on Windows: the build fails naming it instead of reporting it built.
        with mock.patch.object(Path, "unlink", side_effect=PermissionError("in use")):
            step, builds = self.relinked("links")
        self.assertEqual(builds, [])
        self.assertEqual(step.status, Status.FAILED)
        self.assertIn("not relinked: in use", step.detail)


