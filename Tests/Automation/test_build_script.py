class StaleLinkTests(unittest.TestCase):
    """The guard after an MSBuild build (stale_links, relink; the stale Tests.exe of phase 5, which did not reproduce
    in the setup's attempts): an executable older than a first-party static library it links, after a build that
    succeeded, is one whose link MSBuild skipped although the library changed, so Build.py removes it and builds again
    (a full link). The projects are written with premake's shape (the MSBuild namespace, the configuration's
    conditions, OutDir from $(ProjectDir)); every time is set explicitly."""

    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory(prefix="EngineStaleLinks")
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name).resolve()
        (self.root / "Workspace.slnx").write_text(STALE_LINK_SOLUTION, encoding="utf-8")
        output = paths.output_directory_name("Debug")
        condition = "'$(Configuration)|$(Platform)'=='Debug|x64'"
        self.outputs: dict[str, Path] = {}
        for name, (directory, kind, references) in STALE_LINK_PROJECTS.items():
            up = "..\\" * len(Path(directory).parts)
            extension = ".exe" if kind == "Application" else ".lib"
            items = "".join(f'    <ProjectReference Include="{reference}" />\n' for reference in references)
            text = (f'<?xml version="1.0" encoding="utf-8"?>\n'
                    f'<Project DefaultTargets="Build" xmlns="{vendor_cache.MSBUILD_NAMESPACE}">\n'
                    f'  <PropertyGroup Condition="{condition}" Label="Configuration">\n'
                    f'    <ConfigurationType>{kind}</ConfigurationType>\n  </PropertyGroup>\n'
                    f'  <PropertyGroup Condition="{condition}">\n'
                    f'    <OutDir>$(ProjectDir){up}bin\\{output}\\{name}\\</OutDir>\n'
                    f'    <TargetName>{name}</TargetName>\n    <TargetExt>{extension}</TargetExt>\n'
                    f'  </PropertyGroup>\n  <ItemGroup>\n{items}  </ItemGroup>\n</Project>\n')
            (self.root / directory).mkdir(parents=True)
            (self.root / directory / f"{name}.vcxproj").write_text(text, encoding="utf-8")
            self.outputs[name] = self.root / "bin" / output / name / f"{name}{extension}"
            self.outputs[name].parent.mkdir(parents=True)
        self.solution = workspace.read_solution(self.root / "Workspace.slnx")
        # Tests was linked after every library it links changed, the vendored one included.
        for name, seconds in (("Engine", 900), ("EditorCore", 950), ("ImGui", 990), ("Tests", 1000)):
            self.set_output(name, seconds)

    def set_output(self, name: str, seconds: int, data: bytes = b"built") -> None:
        self.outputs[name].write_bytes(data)
        os.utime(self.outputs[name], ns=(seconds * 10**9, seconds * 10**9))

    def stale(self, project: str | None = "Tests") -> list[tuple[str, str]]:
        return [(link.output.name, link.library.name) for link in Build.stale_links(self.solution, "Debug", project)]

    def test_an_output_older_than_a_first_party_library_it_links_is_a_stale_link(self) -> None:
        self.assertEqual(self.stale(), [])
        self.set_output("EditorCore", 1100)
        self.assertEqual(self.stale(), [("Tests.exe", "EditorCore.lib")])
        self.assertEqual(self.stale(None), [("Tests.exe", "EditorCore.lib")], "a build of every project")
        self.assertEqual(self.stale("EditorCore"), [], "a build that links nothing")
        self.set_output("Engine", 1200)
        self.assertEqual(self.stale(), [("Tests.exe", "EditorCore.lib"), ("Tests.exe", "Engine.lib")])

    def test_a_vendored_library_and_a_missing_output_are_not_compared(self) -> None:
        # The vendored libraries come from the vendor cache, where a library in the workspace may be an older build's.
        self.set_output("ImGui", 2000)
        self.assertEqual(self.stale(), [])
        self.set_output("EditorCore", 1100)
        self.outputs["Tests"].unlink()
        self.assertEqual(self.stale(), [], "no output: MSBuild links it")

    def relinked(self, outcome: str) -> tuple[Build.Step, list[str]]:
        """A build step that succeeded, its stale link and a relink whose build `outcome` is "links" (it writes the
        output again, newer than its libraries), "skips" (it leaves the output out), "fails" or "times out"."""
        self.set_output("EditorCore", 1100)
        step = Build.Step("build Debug Tests", Status.PASSED, "Tests built, 0 warnings")
        builds: list[str] = []

        def build() -> tuple[ProcessResult, list[str], list[str]]:
            builds.append("again")
            self.assertFalse(self.outputs["Tests"].exists(), "the stale output is removed first")
            if outcome == "links":
                self.set_output("Tests", 1200, b"relinked")
            elif outcome == "skips":
                self.set_output("Tests", 1000, b"stale")
            if outcome == "times out":
                return ProcessResult(["msbuild"], None, True, 1.0, ""), [], []
            failed = outcome == "fails"
            return (ProcessResult(["msbuild"], 1 if failed else 0, False, 1.0, ""), [],
                    ["LINK : fatal error LNK1104"] if failed else [])

        arguments = mock.Mock(allow_warnings=False, allow_vendor_warnings=False)
        Build.relink(step, Build.stale_links(self.solution, "Debug", "Tests"), build,
                     lambda: Build.stale_links(self.solution, "Debug", "Tests"), self.root, arguments,
                     mock.Mock())
        return step, builds

    def test_a_stale_link_is_linked_again_and_the_build_warns_naming_it(self) -> None:
        step, builds = self.relinked("links")
        self.assertEqual(builds, ["again"])
        self.assertEqual(step.status, Status.WARNING)
        self.assertIn("Tests.exe is older than", step.detail)
        self.assertEqual(self.outputs["Tests"].read_bytes(), b"relinked")
        self.assertEqual([Path(entry["library"]).name for entry in step.data["staleLinks"]], ["EditorCore.lib"])

    def test_a_relink_that_fails_or_leaves_the_output_stale_fails_the_build(self) -> None:
        for outcome in ("skips", "fails"):
            with self.subTest(outcome=outcome):
                step, builds = self.relinked(outcome)
                self.assertEqual(builds, ["again"])
                self.assertEqual(step.status, Status.FAILED)
                self.assertIn("relinking the stale links", step.detail)

    def test_a_relink_that_runs_out_of_time_ends_the_build_as_a_timeout(self) -> None:
        step, builds = self.relinked("times out")
        self.assertEqual(builds, ["again"])
        self.assertEqual(step.status, Status.TIMEOUT)
        self.assertEqual(overall_exit_code([step]), EXIT_TIMEOUT)

    def test_an_output_that_cannot_be_removed_fails_the_build(self) -> None:
        # A running Tests.exe cannot be removed on Windows: the build fails naming it instead of reporting it built.
        with mock.patch.object(Path, "unlink", side_effect=PermissionError("in use")):
            step, builds = self.relinked("links")
        self.assertEqual(builds, [])
        self.assertEqual(step.status, Status.FAILED)
        self.assertIn("not relinked: in use", step.detail)


SECOND = 10**9
# When the inputs of SourceStampTests were last written (2020-09-13), and the time their first build begins
# (2023-11-14): every time below is one of these plus whole seconds, set on the files or given as the builds'
# clock, so no outcome depends on the real clock or its resolution.
WRITTEN = 1_600_000_000 * SECOND
BEGIN = 1_700_000_000

# A bound on the concurrency case's processes, which only bounds a failure.
CONCURRENT_BUILDS_SECONDS = 120.0
# Two builds of one workspace at once, each beginning and ending its source stamps many times (SourceStampTests'
# concurrency case): argv is the Scripts directory, the workspace, the repository and the number of builds.
CONCURRENT_BUILDS = r"""
import sys
sys.path.insert(0, sys.argv[1])
from pathlib import Path
import Build

warnings = []
for _ in range(int(sys.argv[4])):
    stamps = Build.begin_source_stamps(Path(sys.argv[2]), Path(sys.argv[3]))
    Build.end_source_stamps(stamps)
    warnings += stamps.warnings + [f"skipped {name}" for name in stamps.skipped]
print("\n".join(warnings) or "clean", flush=True)
"""


class SourceStampTests(unittest.TestCase):
    """The source stamps Build.py takes as each build begins and ends (begin_source_stamps, end_source_stamps;
    Docs/Architecture.md §2.3, the stale Tests.exe of phase 5): the builds compile what is newer than its objects, so an
    input put back with its older modification time (the kept copy of a fix restored after proving that a regression
    test fails without it) was never compiled again, and Build.py reported Tests built while it ran the code the copy
    had replaced. Every time is explicit (the files' times and the builds' clock, WRITTEN and BEGIN)."""

    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory(prefix="EngineSourceStamps")
        self.addCleanup(temporary.cleanup)
        self.repository = Path(temporary.name).resolve() / "Checkout"
        self.workspace = Path(temporary.name).resolve() / "Workspace"
        # One input of each kind: a source, a header, and the shader rule's .slang file, manifest and shared header.
        self.inputs = {
            "source": self.write("Editor/Source/EditorCore/Commands/Command.cpp", b"int Fixed() { return 1; }\n"),
            "header": self.write("Engine/Source/Engine/Core/Shared.h", b"#pragma once\n#define SHARED 1\n"),
            "shader": self.write("Resources/Shaders/Passes/Scene.slang", b"float4 Shade() { return 1; }\n"),
            "shader manifest": self.write("Resources/Shaders/Shaders.json", b'{"Programs": []}\n'),
            "shader header": self.write("Resources/Shaders/Shared/Common.h", b"#define COMMON 1\n"),
        }
        self.write("Docs/Example.cpp", b"int notCompiled;\n")
        self.write("Engine/Source/Engine/Notes.txt", b"not an input\n")
        self.source = self.inputs["source"]

    def write(self, name: str, data: bytes, modified: int = WRITTEN) -> Path:
        path = self.repository / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        os.utime(path, ns=(modified, modified))
        return path

    def put(self, path: Path, data: bytes, modified: int) -> None:
        self.write(path.relative_to(self.repository).as_posix(), data, modified)

    def name(self, path: Path) -> str:
        return path.relative_to(self.repository).as_posix()

    def begin(self, seconds: int) -> Build.SourceStamps:
        """A build's source stamps as it begins at BEGIN + `seconds`."""
        return Build.begin_source_stamps(self.workspace, self.repository, clock=lambda: (BEGIN + seconds) * SECOND)

    def end(self, stamps: Build.SourceStamps, seconds: int) -> None:
        Build.end_source_stamps(stamps, clock=lambda: (BEGIN + seconds) * SECOND)

    def build(self, begins: int, ends: int) -> Build.SourceStamps:
        stamps = self.begin(begins)
        self.end(stamps, ends)
        return stamps

    def test_the_first_record_touches_nothing_and_covers_every_input(self) -> None:
        first = self.build(0, 10)
        self.assertEqual((first.touched, first.touched_at_end, first.warnings), ([], [], []))
        self.assertEqual(first.files, len(self.inputs), "the C, C++ and shader rule inputs, nothing else")
        self.assertEqual(Build.read_source_record(first.record).files.keys(),
                         {self.name(path) for path in self.inputs.values()})

    def test_an_input_put_back_with_its_older_time_after_a_build_is_given_the_current_one(self) -> None:
        self.build(0, 10)
        for index, (kind, path) in enumerate(self.inputs.items()):
            with self.subTest(kind):
                start = 100 * (index + 1)
                original = path.read_bytes()
                # The fix is reverted (an edit newer than the last build's end), and a build compiles the reverted code.
                self.put(path, original + b"// reverted\n", (BEGIN + start) * SECOND)
                reverted = self.build(start + 10, start + 20)
                self.assertEqual(reverted.touched, [], "an edit newer than the last build's end is the build's own")
                # The kept copy is put back with its own, older time: no build would compile it again.
                self.put(path, original, WRITTEN)
                restored = self.begin(start + 30)
                self.assertEqual(restored.touched, [self.name(path)])
                self.assertEqual(path.stat().st_mtime_ns, (BEGIN + start + 30) * SECOND, "the time the build began")
                self.assertEqual(path.read_bytes(), original, "only the time changes")
                self.end(restored, start + 40)
                self.assertEqual(self.build(start + 50, start + 60).touched, [], "a touched input is touched once")

    def test_a_copy_kept_while_a_build_runs_is_compiled_again(self) -> None:
        # The review's case: a copy of an edit made during a build, put back after a later edit was compiled.
        self.build(0, 10)
        original = self.source.read_bytes()
        stamps = self.begin(20)
        self.put(self.source, b"int Fixed() { return 2; }\n", (BEGIN + 25) * SECOND)  # kept
        self.put(self.source, b"int Fixed() { return 3; }\n", (BEGIN + 26) * SECOND)  # compiled at BEGIN + 28
        self.end(stamps, 30)
        self.assertEqual(stamps.touched_at_end, [self.name(self.source)], "changed while the build ran")
        self.assertEqual(self.source.stat().st_mtime_ns, (BEGIN + 30) * SECOND)
        self.put(self.source, b"int Fixed() { return 2; }\n", (BEGIN + 25) * SECOND)  # the kept copy, put back
        after = self.begin(40)
        self.assertEqual(after.touched, [self.name(self.source)])
        self.end(after, 50)
        # The copy put back while the build still runs: the end of that build gives it the current time.
        during = self.begin(60)
        self.put(self.source, b"int Fixed() { return 4; }\n", (BEGIN + 61) * SECOND)  # compiled at BEGIN + 62
        self.put(self.source, original, WRITTEN)
        self.end(during, 70)
        self.assertEqual(during.touched_at_end, [self.name(self.source)])
        self.assertEqual(self.source.stat().st_mtime_ns, (BEGIN + 70) * SECOND)

    def test_while_another_build_runs_a_changed_input_counts_as_older_than_its_objects(self) -> None:
        self.build(0, 10)
        outer = self.begin(20)
        inner = self.build(30, 40)  # begins and ends while the outer build runs
        self.assertEqual(inner.touched_at_end, [])
        # Put back after the inner build ended, older than what the outer build may still compile.
        self.put(self.source, b"int Fixed() { return 5; }\n", (BEGIN + 45) * SECOND)
        third = self.begin(60)
        self.assertEqual(third.touched, [self.name(self.source)], "the outer build still runs")
        self.end(third, 65)
        self.end(outer, 70)
        # Once every build has ended, an edit newer than the last end is the next build's own.
        self.put(self.source, b"int Fixed() { return 6; }\n", (BEGIN + 75) * SECOND)
        self.assertEqual(self.build(80, 90).touched, [])

    def test_after_a_killed_build_a_changed_input_counts_as_older_than_its_objects(self) -> None:
        self.build(0, 10)
        killed = self.begin(20)
        Build.release_mark(killed)  # the operating system releases a killed build's mark; it never ends
        self.put(self.source, b"int Fixed() { return 7; }\n", (BEGIN + 25) * SECOND)
        after = self.begin(30)
        self.assertEqual(after.touched, [self.name(self.source)])
        self.end(after, 40)

    def test_an_unchanged_input_is_neither_read_nor_touched(self) -> None:
        first = self.build(0, 10)
        self.assertEqual(first.hashed, len(self.inputs))
        with mock.patch.object(Build, "file_sha256", side_effect=AssertionError("an unchanged file was read")):
            unchanged = self.build(20, 30)
        self.assertEqual((unchanged.hashed, unchanged.touched, unchanged.touched_at_end), (0, [], []))
        # The same content written again with an older time is the same code: nothing to compile again.
        self.put(self.source, self.source.read_bytes(), WRITTEN - SECOND)
        same = self.build(40, 50)
        self.assertEqual((same.hashed, same.touched), (1, []))

    def test_an_input_being_saved_is_read_again(self) -> None:
        # An editor that saves through a rename leaves the file missing, or pending deletion, for a moment.
        self.build(0, 10)
        real = Build.file_sha256
        failures = [FileNotFoundError("renamed"), PermissionError("delete pending")]

        def saving(path: Path) -> str:
            if path == self.source and failures:
                raise failures.pop(0)
            return real(path)

        self.put(self.source, b"int Fixed() { return 8; }\n", WRITTEN + SECOND)
        with mock.patch.object(Build, "SOURCE_STAMP_RETRY_SECONDS", 0.0), \
                mock.patch.object(Build, "file_sha256", saving):
            stamps = self.begin(20)
        self.assertEqual((stamps.touched, stamps.skipped, stamps.warnings), ([self.name(self.source)], [], []))
        self.end(stamps, 30)

    def test_an_input_that_stays_unreadable_is_skipped_with_a_warning_naming_it(self) -> None:
        self.build(0, 10)
        real = Build.file_sha256

        def locked(path: Path) -> str:
            if path == self.source:
                raise PermissionError("in use")
            return real(path)

        self.put(self.source, b"int Fixed() { return 9; }\n", WRITTEN + SECOND)
        with mock.patch.object(Build, "SOURCE_STAMP_RETRY_SECONDS", 0.0), \
                mock.patch.object(Build, "file_sha256", locked):
            stamps = self.build(20, 30)
        self.assertEqual(stamps.skipped, [self.name(self.source)] * 2, "as the build began and as it ended")
        self.assertTrue(stamps.warnings and all(self.name(self.source) in warning for warning in stamps.warnings))
        self.assertEqual(stamps.touched, [])
        # Its last readable stamp stays recorded, so the next build that can read it still finds it put back.
        later = self.begin(40)
        self.assertEqual(later.touched, [self.name(self.source)])
        self.end(later, 50)

    def test_an_input_that_cannot_be_touched_is_a_warning_naming_it(self) -> None:
        self.build(0, 10)
        self.put(self.source, b"int Fixed() { return 10; }\n", WRITTEN + SECOND)
        with mock.patch.object(Build, "SOURCE_STAMP_RETRY_SECONDS", 0.0), \
                mock.patch.object(Build.os, "utime", side_effect=PermissionError("read-only")):
            stamps = self.begin(20)
        self.assertEqual(stamps.touched, [])
        self.assertEqual(len(stamps.warnings), 1)
        self.assertIn(self.name(self.source), stamps.warnings[0])
        self.end(stamps, 30)
        # A touch that fails once, then succeeds, is tried again.
        self.put(self.source, b"int Fixed() { return 11; }\n", WRITTEN + 2 * SECOND)
        real = os.utime
        failures = [PermissionError("a scanner has it open")]

        def busy(*arguments: object, **options: object) -> None:
            if failures:
                raise failures.pop(0)
            real(*arguments, **options)  # type: ignore[arg-type]

        with mock.patch.object(Build, "SOURCE_STAMP_RETRY_SECONDS", 0.0), mock.patch.object(Build.os, "utime", busy):
            retried = self.begin(40)
        self.assertEqual((retried.touched, retried.warnings), ([self.name(self.source)], []))
        self.end(retried, 50)

    def test_a_build_that_cannot_take_the_records_lock_warns_and_goes_on(self) -> None:
        self.build(0, 10)
        lock = locks.LockFile(self.workspace / "bin-int" / Build.SOURCE_STAMPS_LOCK_NAME)
        self.assertTrue(lock.try_lock())
        self.addCleanup(lock.unlock, False)
        with mock.patch.object(Build, "SOURCE_STAMPS_LOCK_SECONDS", 0.0):
            stamps = self.begin(20)
            self.end(stamps, 30)
        self.assertEqual((stamps.touched, stamps.files), ([], 0))
        self.assertEqual(len(stamps.warnings), 1)
        self.assertIn(Build.SOURCE_STAMPS_LOCK_NAME, stamps.warnings[0])

    def test_two_builds_of_one_workspace_at_once_never_fail_on_the_record(self) -> None:
        # The review's case: the record written through one fixed temporary name, which two builds of one workspace
        # moved from under each other. Two processes begin and end their stamps many times at once.
        self.build(0, 10)
        command = [sys.executable, "-c", CONCURRENT_BUILDS, str(REPOSITORY_ROOT / "Scripts"), str(self.workspace),
                   str(self.repository), "25"]
        processes = [subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
                                      encoding="utf-8") for _ in range(2)]
        for process in processes:
            output, _ = process.communicate(timeout=CONCURRENT_BUILDS_SECONDS)
            self.assertEqual((process.returncode, output.strip()), (0, "clean"), output)
        intermediate = self.workspace / "bin-int"
        self.assertEqual(sorted(path.name for path in intermediate.glob("*.tmp")), [], "no temporary record is left")
        self.assertEqual(list((intermediate / Build.SOURCE_STAMPS_RUNNING_DIRECTORY).iterdir()), [],
                         "no build's mark is left")
        self.assertEqual(Build.read_source_record(intermediate / Build.SOURCE_STAMPS_FILE_NAME).files.keys(),
                         {self.name(path) for path in self.inputs.values()})

    def test_an_unreadable_record_is_written_again_and_touches_nothing(self) -> None:
        record = self.workspace / "bin-int" / Build.SOURCE_STAMPS_FILE_NAME
        record.parent.mkdir(parents=True)
        record.write_bytes(b"{not json")
        first = self.build(0, 10)
        self.assertEqual((first.files, first.touched), (len(self.inputs), []))
        self.assertEqual(Build.read_source_record(record).files.keys(),
                         {self.name(path) for path in self.inputs.values()})


