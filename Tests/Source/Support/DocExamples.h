// Doc-example type checking (Architecture §11.9; Docs/Decisions/0022-m14-contract.md decision 14). Every fenced block of a
// document whose info string's first word is `lua` or `luau` is an example. Its attributes follow on the info string:
//     ```luau path=Assets/Scripts/Ball.luau prelude=TetrisGame
//     ```lua skip="an excerpt of the generated declarations"
// path= is the example's project path (default Assets/Scripts/DocExample.luau), which its relative requires resolve from;
// prelude= names Tests/Data/TypeChecker/DocExamples/Preludes/<Name>.luau, whose text before its "-- @example" line is put
// before the example and whose text after it follows the example; skip= (a non-empty reason) leaves the block unchecked.
// Requires resolve to the stub modules of Tests/Data/TypeChecker/DocExamples/Assets/ (generated by MakeScriptFixtures.py).

namespace Engine {

	class ScriptApiRegistry;
	class ScriptTypeChecker;
	class TypeRegistry;

	namespace Test {

		// The default project path of an example without path=.
		inline constexpr std::string_view DefaultDocExamplePath = "Assets/Scripts/DocExample.luau";
		// The line of a prelude that stands for the example.
		inline constexpr std::string_view DocExamplePreludeMarker = "-- @example";

		// One Luau block of a document.
		struct DocExampleBlock
		{
			uint32_t FenceLine = 0; // 1-based line of the opening fence; the block's first line is FenceLine + 1
			std::string Path = std::string(DefaultDocExamplePath);
			std::string Prelude{};
			std::optional<std::string> Skip{};
			std::string Source{}; // the block's lines, each ending with '\n', fence indentation removed
		};

		// Every Luau block of the Markdown `text`, in document order. Blocks of other languages are passed over (a Luau
		// fence inside a longer fence of another language is not a block). Errors: Validation located at the line for an
		// unknown attribute, an attribute without a value, an empty skip reason, a path outside Assets/ or not a .luau
		// file, or a fence that is never closed.
		[[nodiscard]] Result<std::vector<DocExampleBlock>> ExtractDocExamples(std::string_view text);

		// One error finding of a checked block.
		struct DocExampleFinding
		{
			// The document line of a finding inside the example; 0 for one in a prelude or a required module.
			uint32_t DocumentLine = 0;
			// "<path>:<line>:<column>" of a finding outside the example (its prelude's file or the module's project path).
			std::string Elsewhere{};
			ScriptDiagnostic Diagnostic{};
		};

		// Checks examples with the engine's strict checker over the generated declarations (RegisterBindings over the
		// builtin registry). Not copyable.
		class DocExampleChecker
		{
		public:
			// Reads the stubs and preludes below `fixtureRoot` (Tests/Data/TypeChecker/DocExamples). Fails the running test
			// case when they cannot be read or the checker cannot be created.
			explicit DocExampleChecker(const std::filesystem::path& fixtureRoot);
			~DocExampleChecker();
			DocExampleChecker(const DocExampleChecker&) = delete;
			DocExampleChecker& operator=(const DocExampleChecker&) = delete;

			// The error findings of `block` (Severity Error), sorted as the checker sorts them. Errors: NotFound for an
			// unknown prelude; Validation for a prelude without exactly one marker line.
			[[nodiscard]] Result<std::vector<DocExampleFinding>> Check(const DocExampleBlock& block) const;
		private:
			struct State;
			Scope<State> m_State{};
		};

	}

}
