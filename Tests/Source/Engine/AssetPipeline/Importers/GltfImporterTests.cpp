				const ImportedArtifact* mesh = FindArtifact(*imported, AssetType::Mesh);
				REQUIRE(mesh != nullptr);
				Result<AssetRef<MeshData>> loaded = LoadCookedMesh(mesh->Cooked);
				REQUIRE_MESSAGE(loaded.has_value(), loaded.error().ToString());
				CHECK(ValidateMeshData(**loaded).has_value());
				for (size_t index = 2; index < imported->Artifacts.size(); ++index)
					CHECK(imported->Artifacts[index - 1].SubAssetKey < imported->Artifacts[index].SubAssetKey);
				Result<AssetRef<PrefabData>> prefab = LoadCookedPrefab(imported->Artifacts.front().Cooked);
