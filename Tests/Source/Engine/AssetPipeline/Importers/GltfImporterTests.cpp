		// Adds `values` (little-endian floats) to `document` as a new data-URI buffer with one SCALAR float accessor over it;
		// returns the accessor's index.
		size_t AddFloatAccessor(Json& document, std::span<const float> values)
		{
			const std::span<const std::byte> bytes = std::as_bytes(values);
			const size_t buffer = document["buffers"].size();
			document["buffers"].push_back({ { "byteLength", bytes.size() }, { "uri", "data:application/octet-stream;base64," + EncodeBase64(bytes) } });
			const size_t view = document["bufferViews"].size();
			document["bufferViews"].push_back({ { "buffer", buffer }, { "byteLength", bytes.size() }, { "byteOffset", 0 } });
			const size_t accessor = document["accessors"].size();
			document["accessors"].push_back({ { "bufferView", view }, { "componentType", 5126 }, { "count", values.size() }, { "type", "SCALAR" } });
			return accessor;
		}

		// Adds `bytes` to `document` as a new data-URI buffer with one accessor over it: `count` elements of glTF accessor type
		// `type` and component type `componentType`, normalized when asked; returns the accessor's index.
		size_t AddAccessor(Json& document, std::span<const std::byte> bytes, int componentType, std::string_view type, size_t count, bool normalized = false)
		{
			const size_t buffer = document["buffers"].size();
			document["buffers"].push_back({ { "byteLength", bytes.size() }, { "uri", "data:application/octet-stream;base64," + EncodeBase64(bytes) } });
			const size_t view = document["bufferViews"].size();
			document["bufferViews"].push_back({ { "buffer", buffer }, { "byteLength", bytes.size() }, { "byteOffset", 0 } });
			const size_t accessor = document["accessors"].size();
			Json entry = { { "bufferView", view }, { "componentType", componentType }, { "count", count }, { "type", std::string(type) } };
			if (normalized)
				entry["normalized"] = true;
			document["accessors"].push_back(std::move(entry));
			return accessor;
		}

		// Adds `values` (little-endian floats, four an element) to `document` as a VEC4 float accessor; returns its index.
		size_t AddVec4Floats(Json& document, std::span<const float> values)
		{
			return AddAccessor(document, std::as_bytes(values), 5126, "VEC4", values.size() / 4);
		}

