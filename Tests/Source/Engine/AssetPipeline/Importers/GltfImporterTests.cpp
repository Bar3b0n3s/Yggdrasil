		// The entity of `document` whose "Name" is `name`.
		Json FindEntity(const Json& document, std::string_view name)
		{
			const Json& entities = document["Entities"];
			for (const Json& entity : entities)
			{
				if (entity["Name"] == Json(std::string(name)))
					return entity;
			}
			FAIL("no entity named '" << std::string(name) << "'");
			return Json();
		}

