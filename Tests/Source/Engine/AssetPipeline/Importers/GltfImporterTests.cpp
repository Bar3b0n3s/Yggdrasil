		void CheckImportFails(const Result<ImportResult>& imported, ErrorCode code, std::initializer_list<std::string_view> fragments)
		{
			REQUIRE_FALSE(imported.has_value());
			const std::string message = imported.error().ToString();
			CAPTURE(message);
			CHECK(imported.error().GetCode() == code);
			for (const std::string_view fragment : fragments)
			{
				CAPTURE(std::string(fragment));
				CHECK(message.find(fragment) != std::string::npos);
			}
		}

