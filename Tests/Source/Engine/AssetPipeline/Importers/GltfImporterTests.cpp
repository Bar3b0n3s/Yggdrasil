		std::string EncodeBase64(std::span<const std::byte> bytes)
		{
			constexpr std::string_view Alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
			std::string text;
			for (size_t i = 0; i < bytes.size(); i += 3)
			{
				const size_t count = std::min<size_t>(3, bytes.size() - i);
				uint32_t group = 0;
				for (size_t k = 0; k < 3; ++k)
					group = (group << 8) | (k < count ? static_cast<uint32_t>(bytes[i + k]) : 0u);
				for (size_t k = 0; k < 4; ++k)
					text.push_back(k <= count ? Alphabet[(group >> (18 - 6 * k)) & 0x3Fu] : '=');
			}
			return text;
		}

		// A glTF document with one node drawing one triangle-list primitive: `positions` (FLOAT VEC3) and `indices` (UNSIGNED_SHORT)
		// in one base64 data-URI buffer, without normals or texture coordinates.
		Json MakeTriangleDocument(std::span<const glm::vec3> positions, std::span<const uint16_t> indices)
		{
			Buffer data(positions.size_bytes() + indices.size_bytes());
			std::memcpy(data.data(), positions.data(), positions.size_bytes());
			std::memcpy(data.data() + positions.size_bytes(), indices.data(), indices.size_bytes());
			while (data.size() % 4 != 0)
				data.push_back(std::byte{ 0 });

			Json position = { { "bufferView", 0 }, { "componentType", 5126 }, { "count", positions.size() }, { "type", "VEC3" } };
			Json index = { { "bufferView", 1 }, { "componentType", 5123 }, { "count", indices.size() }, { "type", "SCALAR" } };
			Json document = Json::object();
			document["asset"] = { { "version", "2.0" } };
			document["buffers"] = Json::array({ { { "byteLength", data.size() }, { "uri", "data:application/octet-stream;base64," + EncodeBase64(data) } } });
			document["bufferViews"] = Json::array({ { { "buffer", 0 }, { "byteLength", positions.size_bytes() }, { "byteOffset", 0 } },
				{ { "buffer", 0 }, { "byteLength", indices.size_bytes() }, { "byteOffset", positions.size_bytes() } } });
			document["accessors"] = Json::array({ position, index });
			Json primitive = { { "attributes", { { "POSITION", 0 } } }, { "indices", 1 } };
			document["meshes"] = Json::array({ { { "name", "Triangles" }, { "primitives", Json::array({ primitive }) } } });
			document["nodes"] = Json::array({ { { "mesh", 0 }, { "name", "Triangles" } } });
			document["scenes"] = Json::array({ { { "nodes", Json::array({ 0 }) } } });
			document["scene"] = 0;
			return document;
		}

