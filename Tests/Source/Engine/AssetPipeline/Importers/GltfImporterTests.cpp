		// Each joint's model transform (parent * T * R * S, parents first) with joint `posed`'s rotation replaced by `rotation`
		// (no joint posed when `posed` is beyond the joints).
		std::vector<glm::mat4> ComputeModelTransforms(const SkeletonData& skeleton, size_t posed = std::numeric_limits<size_t>::max(),
			const glm::quat& rotation = glm::quat(1.0f, 0.0f, 0.0f, 0.0f))
		{
			std::vector<glm::mat4> model;
			for (size_t index = 0; index < skeleton.Joints.size(); ++index)
			{
				const SkeletonJoint& joint = skeleton.Joints[index];
				const glm::mat4 local = glm::translate(glm::mat4(1.0f), joint.Translation) * glm::mat4_cast(index == posed ? rotation : joint.Rotation)
					* glm::scale(glm::mat4(1.0f), joint.Scale);
				model.push_back(joint.Parent >= 0 ? model[static_cast<size_t>(joint.Parent)] * local : local);
			}
			return model;
		}

