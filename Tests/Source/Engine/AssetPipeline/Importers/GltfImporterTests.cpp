			for (const double scale : { 0.0, -1.0 })
			{
				CAPTURE(scale);
				GltfImportSettings value;
				Json json = defaults;
				json["Scale"] = scale;
				CHECK_FALSE(settings->FromJson(&value, JsonReader(json), ReadContext{}).has_value());
			}
			GltfImportSettings value;
			Json json = defaults;
			json["Scale"] = 2.5;
			REQUIRE(settings->FromJson(&value, JsonReader(json), ReadContext{}).has_value());
